using System.Numerics; // WOLFGATE(Savings)
using Content.Client._NF.Bank;
using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.CCVar;
using Content.Shared._NF.Bank;
using Content.Shared._WG.Savings; // WOLFGATE(Savings)
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Prototypes; // WOLFGATE(Savings)

namespace Content.Client._NF.Bank.UI;

[GenerateTypedNameReferences]
public sealed partial class BankATMMenu : FancyWindow
{
    [Dependency] private IEntityManager _ent = default!;
    private readonly BankSystem _bank;
    [Dependency] private IConfigurationManager _cfg = default!;

    public Action? WithdrawRequest;
    public Action? DepositRequest;
    public int Amount;
    public int BankAmount;
    public BankATMMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _bank = _ent.System<BankSystem>();

        WithdrawButton.OnPressed += OnWithdrawPressed;
        DepositButton.OnPressed += OnDepositPressed;
        Title = Loc.GetString("bank-atm-menu-title");
        WithdrawEdit.OnTextChanged += OnAmountChanged;
        InitializeSavings(); // WOLFGATE(Savings)
    }

    // WOLFGATE(Savings) START: the savings transfer row
    /// <summary>Asks to move an amount between bank and savings; true for bank to savings.</summary>
    public Action<int, bool>? SavingsTransferRequest;

    private void InitializeSavings()
    {
        SetSize = MinSize = new Vector2(300, 470);
        ToSavingsButton.OnPressed += _ => RequestSavingsTransfer(true);
        FromSavingsButton.OnPressed += _ => RequestSavingsTransfer(false);

        if (IoCManager.Resolve<IPrototypeManager>().TryIndex(WGSavingsInterestPrototype.Default, out var interest))
        {
            InterestLabel.SetMessage(Loc.GetString("wg-savings-atm-interest",
                ("rate", interest.Rate * 100),
                ("max", BankSystemExtensions.ToSpesoString(interest.InterestOn(interest.BalanceCap)))));
        }
    }

    private void RequestSavingsTransfer(bool toSavings)
    {
        if (int.TryParse(SavingsEdit.Text, out var amount) && amount > 0)
            SavingsTransferRequest?.Invoke(amount, toSavings);
    }
    // WOLFGATE END

    public void SetBalance(int amount, long savings)
    {
        BalanceLabel.Text = BankSystemExtensions.ToSpesoString(amount);
        SavingsLabel.Text = BankSystemExtensions.ToSpesoString(savings);
        BankAmount = amount;
    }

    public void SetDeposit(int amount)
    {
        DepositButton.Disabled = amount <= 0;
        if (amount >= 0) // Valid
        {
            _bank.GetTaxedDepositAmount(amount, BankAmount, out var afterTax, out var taxedAway);
            DepositLabel.Text = BankSystemExtensions.ToSpesoString(afterTax);
            DepositLabelUT.Text = _cfg.GetCVar(MonoCVars.DepositHighExp) == 0 ? Loc.GetString("bank-atm-menu-untaxed") : BankSystemExtensions.ToSpesoString(taxedAway);
        }
        else
        {
            DepositLabel.Text = Loc.GetString("bank-atm-menu-cash-error");
            DepositLabelUT.Text = Loc.GetString("bank-atm-menu-cash-error");
        }
    }

    public void SetEnabled(bool enabled)
    {
        WithdrawButton.Disabled = !enabled;
    }

    private void OnWithdrawPressed(BaseButton.ButtonEventArgs obj)
    {
        WithdrawRequest?.Invoke();
    }

    private void OnDepositPressed(BaseButton.ButtonEventArgs obj)
    {
        DepositRequest?.Invoke();
    }

    private void OnAmountChanged(LineEdit.LineEditEventArgs args)
    {
        if (int.TryParse(args.Text, out var amount))
        {
            Amount = amount;
        }
    }
}
