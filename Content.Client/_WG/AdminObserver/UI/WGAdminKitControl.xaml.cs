using System.Numerics;
using Content.Shared._WG.AdminObserver;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._WG.AdminObserver.UI;

/// <summary>
/// The kit catalogue by group with a search box. Give hands an item to the observer, Put away deletes the held
/// kit item, Save layout stores what it carries now. Items the server had no room for are listed underneath.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WGAdminKitControl : BoxContainer
{
    [Dependency] private IClientConsoleHost _console = default!;
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;

    private const string GiveCommand = "adminkit give";
    private const string PutAwayCommand = "adminkit putaway";

    private static readonly Vector2 IconSize = new(32, 32);

    private readonly WGAdminKitClientSystem _kit;

    public WGAdminKitControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _kit = _entities.System<WGAdminKitClientSystem>();

        UnplacedNote.SetMessage(Loc.GetString("wg-observer-kit-unplaced-note"));
        SearchBar.OnTextChanged += _ => PopulateItems();
        PutAwayButton.OnPressed += _ => _console.ExecuteCommand(PutAwayCommand);
        SaveButton.OnPressed += _ => _kit.RequestSave();

        PopulateItems();
        PopulateUnplaced();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _kit.UnplacedChanged += PopulateUnplaced;
        PopulateUnplaced();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _kit.UnplacedChanged -= PopulateUnplaced;
    }

    private void PopulateItems()
    {
        Items.RemoveAllChildren();
        var search = SearchBar.Text.Trim();

        foreach (var category in _entities.System<WGAdminKitCatalogueSystem>().Categories())
        {
            var header = false;
            foreach (var entry in category.Entries)
            {
                if (!_prototypes.TryIndex(entry, out var prototype) || !Matches(prototype, search))
                    continue;

                if (!header)
                {
                    Items.AddChild(new Label { Text = Loc.GetString(category.Name), StyleClasses = { "LabelKeyText" } });
                    header = true;
                }

                Items.AddChild(Row(prototype, () => Give(prototype.ID)));
            }
        }
    }

    private void PopulateUnplaced()
    {
        UnplacedItems.RemoveAllChildren();
        UnplacedBox.Visible = _kit.Unplaced.Count > 0;

        foreach (var id in _kit.Unplaced)
        {
            if (!_prototypes.TryIndex<EntityPrototype>(id, out var prototype))
                continue;

            UnplacedItems.AddChild(Row(prototype, () =>
            {
                _kit.Forget(id);
                Give(id);
            }));
        }
    }

    private void Give(string id)
    {
        _console.ExecuteCommand($"{GiveCommand} \"{id}\"");
    }

    private static bool Matches(EntityPrototype prototype, string search)
    {
        return search.Length == 0
               || prototype.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase)
               || prototype.ID.Contains(search, StringComparison.OrdinalIgnoreCase);
    }

    private static Control Row(EntityPrototype prototype, Action give)
    {
        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };

        var icon = new EntityPrototypeView
        {
            MinSize = IconSize,
            MaxSize = IconSize,
            Stretch = SpriteView.StretchMode.Fill,
        };
        icon.SetPrototype(prototype.ID);
        row.AddChild(icon);

        row.AddChild(new Label
        {
            Text = prototype.Name,
            HorizontalExpand = true,
            ClipText = true,
            Margin = new Thickness(4, 0),
        });

        var button = new Button { Text = Loc.GetString("wg-observer-kit-give"), StyleClasses = { "ButtonSquare" } };
        button.OnPressed += _ => give();
        row.AddChild(button);
        return row;
    }
}
