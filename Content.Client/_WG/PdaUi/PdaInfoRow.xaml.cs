using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._WG.PdaUi;

/// <summary>
/// One line of details. The server strings already carry their own labels, so the row only
/// renders the value; pressing it copies <see cref="CopyText"/> to the clipboard.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaInfoRow : ContainerButton
{
    public const string StyleClassInfoText = "PdaInfoText";

    private readonly StyleBoxFlat _styleBox = PdaPalette.Box(Color.Transparent);
    private bool _ready;

    public PdaInfoRow()
    {
        RobustXamlLoader.Load(this);
        Background.PanelOverride = _styleBox;
        ValueLabel.ModulateSelfOverride = PdaPalette.TextSoft;
        _ready = true;
    }

    /// <summary>Text the caller should put on the clipboard when the row is pressed.</summary>
    public string CopyText { get; set; } = string.Empty;

    /// <summary>Sets the value with rich text markup, as stored in the PDA state.</summary>
    public void SetValue(string markup)
    {
        ValueLabel.SetMarkup(markup);
    }

    protected override void DrawModeChanged()
    {
        base.DrawModeChanged();
        if (!_ready)
            return;
        _styleBox.BackgroundColor = DrawMode switch
        {
            DrawModeEnum.Pressed => PdaPalette.Pressed,
            DrawModeEnum.Hover => PdaPalette.Hover,
            _ => Color.Transparent,
        };
    }
}
