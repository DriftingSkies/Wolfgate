using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;

namespace Content.Client._WG.PdaUi;

/// <summary>
/// Titled panel matching the Wolfgate Retro window chrome: textured plate and header with an amber title.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaSection : PanelContainer
{
    [Dependency] private IResourceCache _resCache = default!;

    public PdaSection()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var panel = PdaPalette.PanelTexture(_resCache, "window_panel.png", 9);
        panel.SetContentMarginOverride(StyleBox.Margin.All, 4);
        PanelOverride = panel;

        HeaderPanel.PanelOverride = PdaPalette.HeaderTexture(_resCache);

        TitleLabel.FontOverride = PdaPalette.Display(_resCache, 12);
        TitleLabel.FontColorOverride = PdaPalette.Accent;

        XamlChildren = Contents.Children;
    }

    public string? Title
    {
        get => TitleLabel.Text;
        set
        {
            TitleLabel.Text = value ?? string.Empty;
            HeaderPanel.Visible = !string.IsNullOrEmpty(value);
        }
    }

    /// <summary>Container application content should be added to.</summary>
    public BoxContainer Body => Contents;

    /// <summary>Right-aligned header row for section actions.</summary>
    public BoxContainer Buttons => HeaderButtons;
}
