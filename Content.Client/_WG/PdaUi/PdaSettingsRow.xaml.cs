using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client._WG.PdaUi;

/// <summary>
/// Settings entry: icon, title, one-line description and an optional state readout.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaSettingsRow : ContainerButton
{
    [Dependency] private IResourceCache _resCache = default!;

    private readonly StyleBoxFlat _styleBox = PdaPalette.Box(Color.Transparent);
    private bool _ready;

    public PdaSettingsRow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Background.PanelOverride = _styleBox;
        IconRect.Modulate = PdaPalette.IconTint;
        TitleLabel.FontOverride = PdaPalette.Mono(_resCache, 11);
        TitleLabel.FontColorOverride = PdaPalette.TextSoft;
        DescriptionLabel.FontOverride = PdaPalette.Mono(_resCache, 9);
        DescriptionLabel.FontColorOverride = PdaPalette.TextMuted;
        StateLabel.FontOverride = PdaPalette.Mono(_resCache, 10);
        StateLabel.FontColorOverride = PdaPalette.Accent;
        _ready = true;
    }

    public SpriteSpecifier? Icon
    {
        set
        {
            IconRect.Visible = value != null;
            if (value != null)
                PdaIcons.Apply(IconRect, value, 16);
        }
    }

    public string Title
    {
        get => TitleLabel.Text ?? string.Empty;
        set => TitleLabel.Text = value;
    }

    public string? Description
    {
        get => DescriptionLabel.Text;
        set
        {
            DescriptionLabel.Text = value ?? string.Empty;
            DescriptionLabel.Visible = !string.IsNullOrEmpty(value);
        }
    }

    /// <summary>Right-aligned state readout, for example "On" or "Off".</summary>
    public string? State
    {
        get => StateLabel.Visible ? StateLabel.Text : null;
        set
        {
            StateLabel.Text = value ?? string.Empty;
            StateLabel.Visible = !string.IsNullOrEmpty(value);
        }
    }

    protected override void DrawModeChanged()
    {
        base.DrawModeChanged();
        if (!_ready)
            return;
        _styleBox.BackgroundColor = DrawMode switch
        {
            DrawModeEnum.Pressed => PdaPalette.Pressed,
            DrawModeEnum.Hover => PdaPalette.Hover,
            _ => Color.Transparent,
        };
    }
}
