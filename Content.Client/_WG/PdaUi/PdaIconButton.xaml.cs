using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client._WG.PdaUi;

/// <summary>
/// Compact TGUI-style icon button used in the PDA header and navigation strip.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaIconButton : ContainerButton
{
    private readonly StyleBoxFlat _styleBox = PdaPalette.Box(Color.Transparent);
    private bool _isCurrent;
    private bool _isActive = true;
    private bool _ready;

    public Color ActiveFgColor { get; set; } = PdaPalette.Text;
    public Color InactiveFgColor { get; set; } = PdaPalette.TextMuted;

    public PdaIconButton()
    {
        RobustXamlLoader.Load(this);
        Background.PanelOverride = _styleBox;
        _ready = true;
        UpdateColors();
    }

    /// <summary>Sprite drawn before the label.</summary>
    public SpriteSpecifier? Icon
    {
        set
        {
            IconRect.Visible = value != null;
            if (value != null)
                IconRect.SetFromSpriteSpecifier(value);
            UpdateLabelMargin();
        }
    }

    public string? LabelText
    {
        get => Label.Text;
        set
        {
            Label.Text = value ?? string.Empty;
            Label.Visible = !string.IsNullOrEmpty(value);
            UpdateLabelMargin();
        }
    }

    /// <summary>Sets the icon and scales it to the given square size, whatever the source resolution.</summary>
    public void SetIcon(SpriteSpecifier specifier, float size)
    {
        IconRect.Visible = true;
        PdaIcons.Apply(IconRect, specifier, size);
        UpdateLabelMargin();
    }

    /// <summary>Highlights the button as the selected tab.</summary>
    public bool IsCurrent
    {
        get => _isCurrent;
        set
        {
            _isCurrent = value;
            UpdateColors();
        }
    }

    /// <summary>Dims the content when the action is unavailable.</summary>
    public bool IsActive
    {
        get => _isActive;
        set
        {
            _isActive = value;
            UpdateColors();
        }
    }

    protected override void DrawModeChanged()
    {
        base.DrawModeChanged();
        if (!_ready)
            return;
        UpdateColors();
    }

    private void UpdateColors()
    {
        _styleBox.BackgroundColor = DrawMode switch
        {
            DrawModeEnum.Pressed => PdaPalette.Pressed,
            DrawModeEnum.Hover => PdaPalette.Hover,
            _ => _isCurrent ? PdaPalette.Pressed : Color.Transparent,
        };

        var fg = _isActive ? ActiveFgColor : InactiveFgColor;
        IconRect.Modulate = fg;
        Label.FontColorOverride = fg;
    }

    private void UpdateLabelMargin()
    {
        Label.Margin = IconRect.Visible ? new Thickness(4, 0, 0, 0) : new Thickness(0);
    }
}
