using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client._WG.PdaUi;

/// <summary>
/// One row of the TGUI-style program table: icon, name, status and an install/remove action.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaProgramRow : ContainerButton
{
    [Dependency] private IResourceCache _resCache = default!;

    private readonly StyleBoxFlat _styleBox = PdaPalette.Box(Color.Transparent);
    private bool _ready;

    public PdaProgramRow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Background.PanelOverride = _styleBox;
        IconRect.Modulate = PdaPalette.IconTint;
        NameLabel.FontOverride = PdaPalette.Mono(_resCache, 11);
        NameLabel.FontColorOverride = PdaPalette.TextSoft;
        StatusLabel.FontOverride = PdaPalette.Mono(_resCache, 9);
        _ready = true;
    }

    public SpriteSpecifier? Icon
    {
        set
        {
            IconRect.Visible = value != null;
            if (value != null)
                PdaIcons.Apply(IconRect, value, 16);
            NameLabel.Margin = IconRect.Visible ? new Thickness(6, 0, 0, 0) : new Thickness(0);
        }
    }

    public string ProgramName
    {
        get => NameLabel.Text ?? string.Empty;
        set => NameLabel.Text = value;
    }

    /// <summary>Inline status text, for example the running indicator.</summary>
    public string? Status
    {
        get => StatusLabel.Visible ? StatusLabel.Text : null;
        set
        {
            StatusLabel.Text = value ?? string.Empty;
            StatusLabel.Visible = !string.IsNullOrEmpty(value);
        }
    }

    public Color StatusColor
    {
        set => StatusLabel.FontColorOverride = value;
    }

    public PdaButton Action => ActionButton;

    /// <summary>Optional secondary row action, e.g. copying a program to a disk.</summary>
    public PdaButton AltAction => AltButton;

    /// <summary>Entity of the cartridge this row launches; used for the running indicator.</summary>
    public EntityUid ProgramUid { get; set; }

    protected override void DrawModeChanged()
    {
        base.DrawModeChanged();
        if (!_ready)
            return;
        _styleBox.BackgroundColor = DrawMode switch
        {
            DrawModeEnum.Pressed => PdaPalette.Pressed,
            DrawModeEnum.Hover => PdaPalette.Hover,
            _ => Color.Transparent,
        };
    }
}
