using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client._WG.PdaUi;

/// <summary>
/// Wolfgate PDA window: textured bezel, amber title plate, status header, content and footer.
/// Subclasses supply the body through the XAML children of <see cref="ContentsContainer"/>.
/// </summary>
[Virtual]
[GenerateTypedNameReferences]
public partial class PdaOsWindow : BaseWindow
{
    [Dependency] private IResourceCache _resCache = default!;

    private string? _borderColor;
    private string? _accentHColor;
    private string? _accentVColor;

    public PdaOsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        XamlChildren = ContentsContainer.Children;

        FrameTexture.PanelOverride = PdaPalette.PanelTexture(_resCache, "window_panel.png", 9);
        TitleBar.PanelOverride = PdaPalette.HeaderTexture(_resCache);

        TitleLabel.FontOverride = PdaPalette.Display(_resCache, 14);
        TitleLabel.FontColorOverride = PdaPalette.Accent;

        TitleCloseButton.SetIcon(PdaIcons.Close, 14);
        TitleCloseButton.TooltipSupplier = _ => new Tooltip
        {
            Text = Loc.GetString("pda-ui-tooltip-close"),
        };
        TitleCloseButton.OnPressed += _ => Close();

        Scanlines.PanelOverride = PdaPalette.TiledTexture(_resCache, "scanlines.png");
        Scanlines.ModulateSelfOverride = Color.White.WithAlpha(0.05f);

        FooterLabel.FontOverride = PdaPalette.Mono(_resCache, 9);
        FooterLabel.FontColorOverride = PdaPalette.TextDim;
        FooterLabel.Text = Loc.GetString("comp-pda-ui-footer");
        AddressLabel.FontOverride = PdaPalette.Mono(_resCache, 9);
        AddressLabel.FontColorOverride = PdaPalette.TextDim;

        Header.SetOsName(Loc.GetString("pda-ui-os-name"));
        SetTitle(Loc.GetString("pda-ui-title-main"));
        ApplyColors();
    }

    /// <summary>Sets the window title; the Wolfgate mark is used when no program icon is given.</summary>
    public void SetTitle(string title, SpriteSpecifier? icon = null)
    {
        TitleLabel.Text = title;
        PdaIcons.Apply(TitleIcon, icon ?? PdaIcons.Logo, 18);
        TitleIcon.Modulate = PdaPalette.Accent;
    }

    /// <summary>Device body colour, taken from the PDA prototype.</summary>
    public string? BorderColor
    {
        get => _borderColor;
        set
        {
            _borderColor = value;
            ApplyColors();
        }
    }

    /// <summary>Accent line under the header, taken from the PDA prototype.</summary>
    public string? AccentHColor
    {
        get => _accentHColor;
        set
        {
            _accentHColor = value;
            ApplyColors();
        }
    }

    /// <summary>Vertical accent strip on the left edge, taken from the PDA prototype.</summary>
    public string? AccentVColor
    {
        get => _accentVColor;
        set
        {
            _accentVColor = value;
            ApplyColors();
        }
    }

    private void ApplyColors()
    {
        var border = _borderColor != null ? Color.FromHex(_borderColor) : PdaPalette.Border;
        Frame.PanelOverride = PdaPalette.Box(PdaPalette.Base, border, new Thickness(1));

        Footer.PanelOverride = PdaPalette.Box(
            PdaPalette.Base,
            border.WithAlpha(0.5f),
            new Thickness(0, 1, 0, 0));

        var accent = _accentHColor != null ? Color.FromHex(_accentHColor) : PdaPalette.AccentDim;
        Header.SetAccent(accent);

        AccentStrip.Visible = _accentVColor != null;
        if (_accentVColor != null)
            AccentStrip.PanelOverride = PdaPalette.Box(Color.FromHex(_accentVColor));
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        const float margin = 6f;
        var mode = DragMode.None;

        if (relativeMousePos.Y < margin)
            mode |= DragMode.Top;
        else if (relativeMousePos.Y > Size.Y - margin)
            mode |= DragMode.Bottom;

        if (relativeMousePos.X < margin)
            mode |= DragMode.Left;
        else if (relativeMousePos.X > Size.X - margin)
            mode |= DragMode.Right;

        return mode == DragMode.None ? DragMode.Move : mode;
    }
}
