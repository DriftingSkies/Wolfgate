/// <summary>
/// PDA operating system shell: navigation, details, program table and settings.
/// Hosts cartridge fragments supplied by <see cref="CartridgeLoader.CartridgeLoaderBoundUserInterface"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaOsMenu : PdaOsWindow
{
    [Dependency] private IClipboardManager _clipboard = null!;
    [Dependency] private IGameTiming _gameTiming = default!;
    [Dependency] private IEntitySystemManager _entitySystem = default!;
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IResourceCache _resCache = default!;

    private readonly ClientGameTicker _gameTicker;

    private const int HomeViewIndex = 0;
    private const int InfoViewIndex = 1;
    private const int SettingsViewIndex = 2;
    private const int ProgramViewIndex = 3;

    private string _pdaOwner = Loc.GetString("comp-pda-ui-unknown");
    private string _owner = Loc.GetString("comp-pda-ui-unknown");
    private string _jobTitle = Loc.GetString("comp-pda-ui-unassigned");
    private string _stationName = Loc.GetString("comp-pda-ui-unknown");
    private string _alertLevel = Loc.GetString("comp-pda-ui-unknown");
    private string _instructions = Loc.GetString("comp-pda-ui-unknown");
    private string _warLevel = Loc.GetString("comp-pda-ui-station-war-level-unknown");
    private string _balance = Loc.GetString("comp-pda-ui-unknown");
    private string _shuttleDeed = Loc.GetString("comp-pda-ui-unknown");
    private string _currentDate = Loc.GetString("comp-pda-ui-unknown");
    private string _shiftTime = "00:00:00";

    private EntityUid? _activeProgramUid;

    private int _currentView;

    public event Action<EntityUid>? OnProgramItemPressed;
    public event Action<EntityUid>? OnUninstallButtonPressed;
    public event Action<EntityUid>? OnInstallButtonPressed;

    public PdaIconButton FlashLightToggleButton => Header.FlashLightToggleButton;
    public PdaIconButton EjectIdButton => Header.EjectIdButton;
    public PdaIconButton EjectPenButton => Header.EjectPenButton;
    public PdaIconButton EjectPaiButton => Header.EjectPaiButton;
    public PdaIconButton EjectDiskButton => Header.EjectDiskButton; // WOLFGATE(PdaStorage)
    public PdaIconButton ProgramCloseButton => Header.ProgramCloseButton;

    public PdaOsMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _gameTicker = _entitySystem.GetEntitySystem<ClientGameTicker>();

        ConfigureChrome();
        WireInfoRows();
        WireNavigation();

        HideAllViews();
        ToHomeScreen();
    }

    private void ConfigureChrome()
    {
        var nav = PdaPalette.PanelTexture(_resCache, "tab_panel.png", 3);
        nav.SetContentMarginOverride(StyleBox.Margin.All, 0);
        NavBar.PanelOverride = nav;

        HomeButton.SetIcon(PdaIcons.Home, 13);
        HomeButton.LabelText = Loc.GetString("pda-ui-nav-main");

        InfoButton.SetIcon(PdaIcons.Info, 13);
        InfoButton.LabelText = Loc.GetString("pda-ui-nav-info");

        SettingsButton.SetIcon(PdaIcons.Settings, 13);
        SettingsButton.LabelText = Loc.GetString("comp-pda-io-settings-button");

        NoProgramsLabel.Text = Loc.GetString("comp-pda-io-no-programs-available");
        NoProgramsLabel.FontColorOverride = PdaPalette.TextMuted;
        NoProgramsLabel.HorizontalAlignment = HAlignment.Center;
        NoProgramsLabel.Margin = new Thickness(0, 8);

        Header.HomeButton.OnPressed += _ => ToHomeScreen();
    }

    private void WireInfoRows()
    {
        WireInfoRow(PdaOwnerLabel, () => _pdaOwner);
        WireInfoRow(IdInfoLabel, () => _owner + ", " + _jobTitle);
        WireInfoRow(StationNameLabel, () => _stationName);
        WireInfoRow(StationAlertLevelLabel, () => _alertLevel);
        WireInfoRow(StationAlertLevelInstructions, () => _instructions);
        WireInfoRow(WarLevelLabel, () => _warLevel);
        WireInfoRow(StationTimeLabel, () => _shiftTime);
        WireInfoRow(CurrentDateLabel, () => _currentDate);
        WireInfoRow(BalanceLabel, () => _balance);
        WireInfoRow(ShuttleDeedLabel, () => _shuttleDeed);
    }

    private void WireInfoRow(PdaInfoRow row, Func<string> copyText)
    {
        row.OnPressed += _ => _clipboard.SetText(copyText());
    }

    private void WireNavigation()
    {
        HomeButton.OnPressed += _ => ToHomeScreen();
        InfoButton.OnPressed += _ => ToInfo();
        SettingsButton.OnPressed += _ => ToSettings();
    }

    public void UpdateState(PdaUpdateState state)
    {
        Header.FlashLightToggleButton.IsActive = state.FlashlightEnabled;

        if (state.PdaOwnerInfo.ActualOwnerName != null)
        {
            _pdaOwner = state.PdaOwnerInfo.ActualOwnerName;

            if (!string.IsNullOrWhiteSpace(state.PdaOwnerInfo.CompanyName))
            {
                PdaOwnerLabel.SetValue(Loc.GetString("comp-pda-ui-owner-with-company",
                    ("actualOwnerName", _pdaOwner),
                    ("companyName", state.PdaOwnerInfo.CompanyName),
                    ("companyColor", state.PdaOwnerInfo.CompanyColor.ToHex())));
            }
            else
            {
                PdaOwnerLabel.SetValue(Loc.GetString("comp-pda-ui-owner",
                    ("actualOwnerName", _pdaOwner)));
            }

            PdaOwnerLabel.Visible = true;
        }
        else
        {
            PdaOwnerLabel.Visible = false;
        }

        if (state.PdaOwnerInfo.IdOwner != null || state.PdaOwnerInfo.JobTitle != null)
        {
            _owner = state.PdaOwnerInfo.IdOwner ?? Loc.GetString("comp-pda-ui-unknown");
            _jobTitle = state.PdaOwnerInfo.JobTitle ?? Loc.GetString("comp-pda-ui-unassigned");
            IdInfoLabel.SetValue(Loc.GetString("pda-ui-row-assignment",
                ("owner", _owner),
                ("jobTitle", _jobTitle)));
            IdInfoLabel.Visible = true;
        }
        else
        {
            IdInfoLabel.Visible = false;
        }

        _stationName = state.StationName ?? Loc.GetString("comp-pda-ui-unknown");
        StationNameLabel.SetValue(Loc.GetString("comp-pda-ui-station", ("station", _stationName)));

        _balance = BankSystemExtensions.ToSpesoString(state.Balance);
        BalanceLabel.SetValue(Loc.GetString("comp-pda-ui-balance", ("balance", _balance)));

        _shuttleDeed = state.OwnedShipName ?? string.Empty;
        ShuttleDeedLabel.SetValue(Loc.GetString("comp-pda-ui-shuttle-deed", ("shipname", _shuttleDeed)));
        ShuttleDeedLabel.Visible = !string.IsNullOrEmpty(state.OwnedShipName);

        var alertLevel = state.PdaOwnerInfo.StationAlertLevel;
        var alertColor = state.PdaOwnerInfo.StationAlertColor;
        var alertLevelKey = alertLevel != null ? $"alert-level-{alertLevel}" : "alert-level-unknown";
        _alertLevel = Loc.GetString(alertLevelKey);

        StationAlertLevelLabel.SetValue(Loc.GetString(
            "comp-pda-ui-station-alert-level",
            ("color", alertColor),
            ("level", _alertLevel)));

        _instructions = Loc.GetString($"{alertLevelKey}-instructions");
        StationAlertLevelInstructions.SetValue(Loc.GetString(
            "comp-pda-ui-station-alert-level-instructions",
            ("instructions", _instructions)));

        if (state.PdaOwnerInfo.CurrentDate is { } currentDate)
            _currentDate = currentDate.ToString("dd/MM/yyyy");

        CurrentDateLabel.SetValue(Loc.GetString("comp-pda-ui-current-date", ("date", _currentDate)));

        _warLevel = state.PdaOwnerInfo.WarLevel ?? Loc.GetString("comp-pda-ui-station-war-level-unknown");
        WarLevelLabel.SetValue(_warLevel);

        Header.SetAlert(alertLevel != null ? _alertLevel : null, alertColor);

        AddressLabel.Text = state.Address?.ToUpper() ?? " - ";

        SetActiveProgram(_entManager.GetEntity(state.ActiveUI));
        Header.EjectIdButton.IsActive = state.PdaOwnerInfo.IdOwner != null || state.PdaOwnerInfo.JobTitle != null;
        Header.EjectPenButton.IsActive = state.HasPen;
        Header.EjectPaiButton.IsActive = state.HasPai;
        Header.EjectDiskButton.IsActive = state.HasDisk; // WOLFGATE(PdaStorage)
        ActivateMusicButton.Visible = state.CanPlayMusic;
        ShowUplinkButton.Visible = state.HasUplink;
        LockUplinkButton.Visible = state.HasUplink;
        NotificationsButton.State = state.NotificationsEnabled
            ? Loc.GetString("pda-ui-toggle-on")
            : Loc.GetString("pda-ui-toggle-off");
    }

    public void UpdateAvailablePrograms(List<(EntityUid, CartridgeComponent)> programs)
    {
        ProgramList.RemoveAllChildren();
        NoProgramsLabel.Visible = programs.Count == 0;

        foreach (var (uid, component) in programs)
        {
            var row = new PdaProgramRow
            {
                ProgramName = Loc.GetString(component.ProgramName),
                ProgramUid = uid,
                Icon = PdaProgramIcons.Get(component.ProgramName) ?? component.Icon,
            };

            row.OnPressed += _ => OnProgramItemPressed?.Invoke(uid);

            switch (component.InstallationStatus)
            {
                case InstallationStatus.Cartridge:
                    row.Action.Visible = true;
                    row.Action.Text = Loc.GetString("cartridge-bound-user-interface-install-button");
                    row.Action.OnPressed += _ => OnInstallButtonPressed?.Invoke(uid);
                    break;
                case InstallationStatus.Installed:
                    row.Action.Visible = true;
                    row.Action.Text = Loc.GetString("cartridge-bound-user-interface-uninstall-button");
                    row.Action.OnPressed += _ => OnUninstallButtonPressed?.Invoke(uid);
                    break;
            }

            ProgramList.AddChild(row);
        }

        HighlightActiveProgram();
    }

    /// <summary>Marks the program whose UI is hosted as running.</summary>
    public void SetActiveProgram(EntityUid? program)
    {
        _activeProgramUid = program;
        HighlightActiveProgram();
    }

    /// <summary>Marks the program whose UI is hosted as running.</summary>
    private void HighlightActiveProgram()
    {
        foreach (var child in ProgramList.Children)
        {
            if (child is not PdaProgramRow row)
                continue;

            var running = _activeProgramUid.HasValue && row.ProgramUid == _activeProgramUid.Value;
            row.Status = running ? Loc.GetString("pda-ui-status-running") : null;
            row.StatusColor = PdaPalette.Accent;
        }
    }

    /// <summary>Switches to the main view and updates the navigation state.</summary>
    public void ToHomeScreen()
    {
        HomeButton.IsCurrent = true;
        InfoButton.IsCurrent = false;
        SettingsButton.IsCurrent = false;

        SetTitle(Loc.GetString("pda-ui-title-main"));
        Header.SetProgramOpen(false);
        NavBar.Visible = true;
        ChangeView(HomeViewIndex);
    }

    /// <summary>Switches to the detailed information view and updates the navigation state.</summary>
    public void ToInfo()
    {
        HomeButton.IsCurrent = false;
        InfoButton.IsCurrent = true;
        SettingsButton.IsCurrent = false;

        SetTitle(Loc.GetString("pda-ui-title-info"));
        Header.SetProgramOpen(false);
        NavBar.Visible = true;
        ChangeView(InfoViewIndex);
    }

    /// <summary>Switches to the settings view and updates the navigation state.</summary>
    public void ToSettings()
    {
        HomeButton.IsCurrent = false;
        InfoButton.IsCurrent = false;
        SettingsButton.IsCurrent = true;

        SetTitle(Loc.GetString("pda-ui-title-settings"));
        Header.SetProgramOpen(false);
        NavBar.Visible = true;
        ChangeView(SettingsViewIndex);
    }

    /// <summary>Reveals the navigation strip after a program closes.</summary>
    public void HideProgramHeader()
    {
        Header.SetProgramOpen(false);
        NavBar.Visible = true;
    }

    /// <summary>Switches to the hosted program view and titles it in the window bar.</summary>
    public void ToProgramView(string title, SpriteSpecifier? icon = null)
    {
        HomeButton.IsCurrent = false;
        InfoButton.IsCurrent = false;
        SettingsButton.IsCurrent = false;

        SetTitle(title, icon);
        Header.SetProgramOpen(true);
        NavBar.Visible = false;
        ChangeView(ProgramViewIndex);
    }

    /// <summary>Changes the visible view by index.</summary>
    public void ChangeView(int view)
    {
        if (ViewContainer.ChildCount <= view)
            return;

        if (_currentView < ViewContainer.ChildCount)
            ViewContainer.GetChild(_currentView).Visible = false;

        ViewContainer.GetChild(view).Visible = true;
        _currentView = view;
    }

    private void HideAllViews()
    {
        foreach (var view in ViewContainer.Children)
        {
            view.Visible = false;
        }
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        var stationTime = _gameTiming.CurTime.Subtract(_gameTicker.RoundStartTimeSpan);
        _shiftTime = stationTime.ToString("hh\\:mm\\:ss");

        StationTimeLabel.SetValue(Loc.GetString("comp-pda-ui-station-time", ("time", _shiftTime)));
        Header.SetTime(_shiftTime);
    }
}
