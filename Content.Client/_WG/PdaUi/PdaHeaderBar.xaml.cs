using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;

namespace Content.Client._WG.PdaUi;

/// <summary>
/// Wolfgate status header: shift clock, OS label, and the device buttons.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaHeaderBar : PanelContainer
{
    [Dependency] private IResourceCache _resCache = default!;

    private Color _accent = PdaPalette.Border;

    public PdaHeaderBar()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ApplyBackground();

        ClockIcon.SetSize = new Vector2(14, 14);
        PdaIcons.Apply(ClockIcon, PdaIcons.Clock, 14);

        TimeLabel.FontOverride = PdaPalette.Mono(_resCache, 11);
        TimeLabel.FontColorOverride = PdaPalette.Text;
        OsLabel.FontOverride = PdaPalette.SansItalic(_resCache, 10);
        OsLabel.FontColorOverride = PdaPalette.TextMuted.WithAlpha(0.55f);

        AlertLabel.FontOverride = PdaPalette.Mono(_resCache, 10);

        FlashLightToggleButton.SetIcon(PdaIcons.Light, 15);
        FlashLightToggleButton.ActiveFgColor = PdaPalette.Caution;
        FlashLightToggleButton.TooltipSupplier = _ => new Tooltip { Text = Loc.GetString("comp-pda-ui-toggle-flashlight-button") };

        EjectPenButton.SetIcon(PdaIcons.Pen, 15);
        EjectPenButton.TooltipSupplier = _ => new Tooltip { Text = Loc.GetString("comp-pda-ui-eject-pen-button") };

        EjectIdButton.SetIcon(PdaIcons.Id, 15);
        EjectIdButton.TooltipSupplier = _ => new Tooltip { Text = Loc.GetString("comp-pda-ui-eject-id-button") };

        EjectPaiButton.SetIcon(PdaIcons.Pai, 15);
        EjectPaiButton.TooltipSupplier = _ => new Tooltip { Text = Loc.GetString("pda-ui-tooltip-eject-pai") };

        EjectDiskButton.SetIcon(PdaIcons.Eject, 15);
        EjectDiskButton.TooltipSupplier = _ => new Tooltip { Text = Loc.GetString("pda-ui-tooltip-eject-disk") };

        HomeButton.SetIcon(PdaIcons.Home, 15);
        HomeButton.TooltipSupplier = _ => new Tooltip { Text = Loc.GetString("pda-ui-tooltip-home") };

        ProgramCloseButton.SetIcon(PdaIcons.Close, 15);
        ProgramCloseButton.TooltipSupplier = _ => new Tooltip { Text = Loc.GetString("pda-ui-tooltip-close-program") };
    }

    /// <summary>Paints the header strip, changing the dividing line to the device accent.</summary>
    public void SetAccent(Color accent)
    {
        _accent = accent;
        ApplyBackground();
    }

    private void ApplyBackground()
    {
        PanelOverride = PdaPalette.Box(PdaPalette.HeaderBar, _accent, new Thickness(0, 0, 0, 1));
    }

    public void SetTime(string time)
    {
        TimeLabel.Text = time;
    }

    public void SetOsName(string name)
    {
        OsLabel.Text = name;
    }

    /// <summary>Shows the close-program button while a cartridge UI is hosted.</summary>
    public void SetProgramOpen(bool open)
    {
        ProgramCloseButton.Visible = open;
    }

    /// <summary>Shows the current alert level chip in the header, or hides it when null.</summary>
    public void SetAlert(string? text, Color color)
    {
        AlertChip.Visible = !string.IsNullOrEmpty(text);
        if (string.IsNullOrEmpty(text))
            return;

        AlertLabel.Text = text;
        AlertLabel.FontColorOverride = Luminance(color) > 0.55f ? Color.Black : Color.White;
        AlertChip.PanelOverride = PdaPalette.Box(color);
        AlertChip.TooltipSupplier = _ => new Tooltip
        {
            Text = Loc.GetString("pda-ui-tooltip-alert"),
        };
    }

    private static float Luminance(Color color)
    {
        return color.R * 0.299f + color.G * 0.587f + color.B * 0.114f;
    }
}
