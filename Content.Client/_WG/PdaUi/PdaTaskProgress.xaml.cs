using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;

namespace Content.Client._WG.PdaUi;

/// <summary>
/// Bordered progress readout in the Wolfgate retro style: a fill bar with a centred label. Used for download
/// buttons that turn into a percentage box and for the storage capacity line.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaTaskProgress : Control
{
    [Dependency] private IResourceCache _resCache = default!;

    public PdaTaskProgress()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Bar.BackgroundStyleBoxOverride = PdaPalette.Box(PdaPalette.Surface, PdaPalette.Good, new Thickness(1));
        Bar.ForegroundStyleBoxOverride = PdaPalette.Box(PdaPalette.Good.WithAlpha(0.35f));
        Bar.MinValue = 0;
        Bar.MaxValue = 1;

        TextLabel.FontOverride = PdaPalette.Mono(_resCache, 10);
        TextLabel.FontColorOverride = PdaPalette.Text;
    }

    public string? Text
    {
        get => TextLabel.Text;
        set => TextLabel.Text = value ?? string.Empty;
    }

    /// <summary>Sets the filled fraction; values outside the range are clamped.</summary>
    public void SetProgress(float value, float max)
    {
        Bar.MaxValue = MathF.Max(1f, max);
        Bar.Value = Math.Clamp(value, 0f, Bar.MaxValue);
    }
}
