using Robust.Client.AutoGenerated;
using Content.Client.Resources;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;

namespace Content.Client._WG.PdaUi;

/// <summary>
/// Small textured button in the Wolfgate Retro style, tinted per state, sized for inline row actions.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaButton : ContainerButton
{
    [Dependency] private IResourceCache _resCache = default!;

    private readonly StyleBoxTexture _styleBox = new();
    private bool _ready;

    public PdaButton()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _styleBox.Texture = _resCache.GetTexture(PdaPalette.SkinPath + "button.png");
        _styleBox.SetPatchMargin(StyleBox.Margin.All, 10);
        _styleBox.SetContentMarginOverride(StyleBox.Margin.Vertical, 2);
        _styleBox.SetContentMarginOverride(StyleBox.Margin.Horizontal, 8);
        Background.PanelOverride = _styleBox;

        TextLabel.FontOverride = PdaPalette.Mono(_resCache, 10);
        _ready = true;
        UpdateColors();
    }

    public string? Text
    {
        get => TextLabel.Text;
        set => TextLabel.Text = value ?? string.Empty;
    }

    protected override void DrawModeChanged()
    {
        base.DrawModeChanged();
        if (!_ready)
            return;
        UpdateColors();
    }

    private void UpdateColors()
    {
        if (Disabled)
        {
            _styleBox.Modulate = PdaPalette.SurfaceRaised;
            TextLabel.FontColorOverride = PdaPalette.TextDim;
            return;
        }

        _styleBox.Modulate = DrawMode switch
        {
            DrawModeEnum.Pressed => PdaPalette.Pressed,
            DrawModeEnum.Hover => PdaPalette.Hover,
            _ => PdaPalette.Primary,
        };
        TextLabel.FontColorOverride = PdaPalette.Text;
    }
}
