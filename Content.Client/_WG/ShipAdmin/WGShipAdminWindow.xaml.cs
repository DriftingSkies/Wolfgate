/// <summary>How Shipmaster orders its list of ships.</summary>
public enum WGShipAdminSort : byte
{
    /// <summary>The ship the viewer is on, then ships on their map by distance, then the rest by name.</summary>
    Nearest,
    Name,
    Owner,
    Aboard,
}

/// <summary>Shipmaster, the admin ship panel: a list of ships on the left, the selected ship's tabs on the right.</summary>
[GenerateTypedNameReferences]
public sealed partial class WGShipAdminWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IEyeManager _eye = default!;
    [Dependency] private IPlayerManager _player = default!;

    /// <summary>How often the arrows and distances are brought up to date. They read the client's own view, no message.</summary>
    private const float CompassInterval = 0.25f;

    /// <summary>Raised with a message for the server.</summary>
    public event Action<EuiMessageBase>? OnMessage;

    private readonly List<WGShipAdminTab> _tabs = new();
    private readonly List<ShipRow> _rows = new();
    private List<WGShipAdminRow> _ships = new();
    private WGShipAdminDetail? _detail;
    private bool _truncated;
    private WGShipAdminFilter _filter;
    private WGShipAdminSort _sort = WGShipAdminSort.Nearest;
    private NetEntity? _selected;
    private int _resultSeq = -1;
    private float _compassTimer;
    private int _headerShown = Unset;
    private SharedTransformSystem? _xforms;

    private const int Unset = -3;
    private const int Blank = -2;
    private const int Here = -1;

    /// <summary>The overview tab, for tests.</summary>
    public readonly WGShipAdminOverviewTab Overview = new();

    /// <summary>The ownership tab, for tests.</summary>
    public readonly WGShipAdminOwnershipTab Ownership = new();

    /// <summary>The access tab, for tests.</summary>
    public readonly WGShipAdminAccessTab Access = new();

    /// <summary>The repair tab, for tests.</summary>
    public readonly WGShipAdminRepairTab Repair = new();

    /// <summary>The move tab, for tests.</summary>
    public readonly WGShipAdminMoveTab Move = new();

    /// <summary>The systems, upgrades and danger tabs, for tests.</summary>
    public readonly WGShipAdminSystemsTab Systems = new();
    public readonly WGShipAdminUpgradesTab Upgrades = new();
    public readonly WGShipAdminDangerTab Danger = new();

    public WGShipAdminWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        AddTab(Overview);
        AddTab(Ownership);
        AddTab(Access);
        AddTab(Repair);
        AddTab(Move);
        AddTab(Systems);
        AddTab(Upgrades);
        AddTab(Danger);

        ShipSummaryLabel.Colour = WGShipAdminText.Subdued;
        foreach (var sort in Enum.GetValues<WGShipAdminSort>())
            SortButton.AddItem(Loc.GetString($"wg-ship-admin-sort-{sort.ToString().ToLowerInvariant()}"), (int) sort);

        SortButton.SelectId((int) _sort);
        SortButton.OnItemSelected += args =>
        {
            _sort = (WGShipAdminSort) args.Id;
            Populate();
        };

        SearchBar.OnTextChanged += _ => Populate();
        RefreshButton.OnPressed += _ => OnMessage?.Invoke(new WGShipAdminListMessage(_filter));
        PlayerShipsButton.OnPressed += _ => OnMessage?.Invoke(new WGShipAdminListMessage(WGShipAdminFilter.PlayerShips));
        AllGridsButton.OnPressed += _ => OnMessage?.Invoke(new WGShipAdminListMessage(WGShipAdminFilter.AllGrids));
    }

    private SharedTransformSystem Xforms => _xforms ??= _entMan.System<SharedTransformSystem>();

    private void AddTab(WGShipAdminTab tab)
    {
        _tabs.Add(tab);
        Tabs.AddChild(tab);
        TabContainer.SetTabTitle(tab, tab.Title);
        tab.OnMessage += message => OnMessage?.Invoke(message);
    }

    public void UpdateState(WGShipAdminEuiState state)
    {
        _filter = state.Filter;
        PlayerShipsButton.Pressed = _filter == WGShipAdminFilter.PlayerShips;
        AllGridsButton.Pressed = _filter == WGShipAdminFilter.AllGrids;

        var selected = state.Selected?.Grid;
        if (state.Ships != null || selected != _selected)
        {
            if (state.Ships != null)
            {
                _ships = state.Ships;
                _truncated = state.Truncated;
                foreach (var tab in _tabs)
                    tab.SetShips(_ships);
            }

            _selected = selected;
            Populate();
        }

        _detail = state.Selected;
        _headerShown = Unset;
        NoShipLabel.Visible = state.Selected == null;
        ShipBox.Visible = state.Selected != null;
        if (state.Selected is { } detail)
        {
            ShipNameLabel.Text = detail.Name;
            ShipSummaryLabel.Text = Loc.GetString("wg-ship-admin-summary",
                ("owner", detail.RecordOwner.Length > 0 ? detail.RecordOwner : Loc.GetString("wg-ship-admin-unowned")),
                ("map", detail.Map),
                ("aboard", detail.OccupantCount));

            foreach (var tab in _tabs)
                tab.Update(detail, state.ViewerFlags);
        }

        if (state.ResultSeq != _resultSeq)
        {
            _resultSeq = state.ResultSeq;
            ResultLabel.Colour = state.ResultError ? Color.FromHex("#E05A5A") : null;
            ResultLabel.Text = state.Result;
        }

        UpdateCompasses();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        _compassTimer += args.DeltaSeconds;
        if (_compassTimer < CompassInterval)
            return;

        _compassTimer = 0f;
        UpdateCompasses();
    }

    /// <summary>
    /// Orders a list of ships in place. <paramref name="here"/> is the ship the viewer is on, and
    /// <paramref name="map"/> and <paramref name="position"/> where they are; with no map, nearest falls back to name.
    /// </summary>
    public static void Sort(List<WGShipAdminRow> ships, WGShipAdminSort sort, NetEntity? here, MapId? map, Vector2 position)
    {
        if (sort == WGShipAdminSort.Nearest && map == null)
            sort = WGShipAdminSort.Name;

        ships.Sort((a, b) =>
        {
            var order = sort switch
            {
                WGShipAdminSort.Nearest => Nearness(a, here, map, position).CompareTo(Nearness(b, here, map, position)),
                WGShipAdminSort.Owner => CompareOwners(a, b),
                WGShipAdminSort.Aboard => b.Occupants.CompareTo(a.Occupants),
                _ => 0,
            };

            return order != 0 ? order : string.Compare(a.Name, b.Name, StringComparison.CurrentCultureIgnoreCase);
        });
    }

    /// <summary>Owned ships by owner name, then the ships nobody owns.</summary>
    private static int CompareOwners(WGShipAdminRow a, WGShipAdminRow b)
    {
        var owned = (a.Owner.Length == 0).CompareTo(b.Owner.Length == 0);
        return owned != 0 ? owned : string.Compare(a.Owner, b.Owner, StringComparison.CurrentCultureIgnoreCase);
    }

    /// <summary>Lower sorts first: the viewer's own ship, then ships on their map by distance, then every other map.</summary>
    private static float Nearness(WGShipAdminRow ship, NetEntity? here, MapId? map, Vector2 position)
    {
        if (ship.Grid == here)
            return -1f;

        return ship.MapId == map ? (ship.Position - position).LengthSquared() : float.MaxValue;
    }

    /// <summary>Rebuilds the rows from the last list, the sort, the search text and the selection.</summary>
    private void Populate()
    {
        ShipList.RemoveAllChildren();
        _rows.Clear();

        var viewer = TryViewer(out var map, out var position, out var here);
        if (_sort == WGShipAdminSort.Nearest)
        {
            // A ship in view is where the client sees it now; the list only has where it was when it was built.
            foreach (var ship in _ships)
                (ship.MapId, ship.Position) = Locate(ship.Grid, ship.MapId, ship.Position);
        }

        Sort(_ships, _sort, here, viewer ? map : null, position);

        var search = SearchBar.Text.Trim().ToLowerInvariant();
        var shown = 0;
        foreach (var ship in _ships)
        {
            if (search.Length > 0
                && !ship.Name.ToLowerInvariant().Contains(search)
                && !ship.Owner.ToLowerInvariant().Contains(search)
                && !ship.Design.ToLowerInvariant().Contains(search))
                continue;

            ShipList.AddChild(MakeRow(ship));
            shown++;
        }

        if (_ships.Count == 0)
            ShipList.AddChild(new Label { Text = Loc.GetString("wg-ship-admin-empty"), Margin = new Thickness(6) });

        CountLabel.Text = Loc.GetString(_truncated ? "wg-ship-admin-count-truncated" : "wg-ship-admin-count", ("shown", shown), ("total", _ships.Count));
        UpdateCompasses();
    }

    private Control MakeRow(WGShipAdminRow ship)
    {
        var labels = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };
        labels.AddChild(new Label { Text = ship.Name, ClipText = true });
        labels.AddChild(new Label
        {
            Text = Loc.GetString("wg-ship-admin-row",
                ("owner", ship.Owner.Length > 0 ? ship.Owner : Loc.GetString("wg-ship-admin-unowned")),
                ("state", ship.OwnerState.ToString().ToLowerInvariant()),
                ("aboard", ship.Occupants)),
            StyleClasses = { "LabelSubText" },
            ClipText = true,
        });

        var compass = new WGShipAdminCompass();
        var distance = new Label { StyleClasses = { "LabelSubText" }, SetWidth = 58, Align = Label.AlignMode.Right, ClipText = true };
        var line = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 6,
            Margin = new Thickness(4, 1),
        };
        line.AddChild(compass);
        line.AddChild(labels);
        line.AddChild(distance);

        var button = new ContainerButton
        {
            ToggleMode = true,
            Pressed = ship.Grid == _selected,
            HorizontalExpand = true,
            ToolTip = ship.Map,
        };
        button.AddStyleClass(ContainerButton.StyleClassButton);
        button.AddChild(line);

        var grid = ship.Grid;
        button.OnPressed += _ => OnMessage?.Invoke(new WGShipAdminSelectMessage(grid));
        _rows.Add(new ShipRow(ship, compass, distance));
        return button;
    }

    /// <summary>
    /// Points every row's arrow, and the header's, at its ship and writes how far it is. A label is only written
    /// when its whole-metre distance changed, so a still viewer costs no layout.
    /// </summary>
    private void UpdateCompasses()
    {
        var viewer = TryViewer(out var map, out var position, out var here);
        var origin = viewer ? _eye.WorldToScreen(position) : default;
        foreach (var row in _rows)
            row.Shown = Point(row.Compass, row.Distance, row.Shown, row.Ship.Grid, row.Ship.MapId, row.Ship.Position, viewer, map, position, here, origin);

        if (_detail is { } detail)
            _headerShown = Point(HeaderCompass, HeaderDistance, _headerShown, detail.Grid, detail.MapId, detail.Position, viewer, map, position, here, origin);
    }

    private int Point(WGShipAdminCompass compass, Label distance, int shown, NetEntity grid, MapId listedMap, Vector2 listedPosition,
        bool viewer, MapId map, Vector2 position, NetEntity? here, Vector2 origin)
    {
        int now;
        if (!viewer)
        {
            compass.Clear();
            now = Blank;
        }
        else if (grid == here)
        {
            compass.Here();
            now = Here;
        }
        else
        {
            var (shipMap, shipPosition) = Locate(grid, listedMap, listedPosition);
            if (shipMap != map)
            {
                compass.Clear();
                now = Blank;
            }
            else
            {
                compass.Point(_eye.WorldToScreen(shipPosition) - origin);
                now = (int) MathF.Round((shipPosition - position).Length());
            }
        }

        if (now == shown)
            return now;

        distance.Text = now switch
        {
            Blank => string.Empty,
            Here => Loc.GetString("wg-ship-admin-compass-here"),
            _ => Loc.GetString("wg-ship-admin-compass-distance", ("distance", now)),
        };
        return now;
    }

    /// <summary>Where the viewer's body is, and the ship it is on. False in the lobby or with no body on a map.</summary>
    private bool TryViewer(out MapId map, out Vector2 position, out NetEntity? here)
    {
        map = MapId.Nullspace;
        position = default;
        here = null;
        if (_player.LocalEntity is not { } body
            || !_entMan.TryGetComponent(body, out TransformComponent? xform)
            || xform.MapID == MapId.Nullspace)
            return false;

        map = xform.MapID;
        position = Xforms.GetWorldPosition(xform);
        if (xform.GridUid is { } on)
            here = _entMan.GetNetEntity(on);

        return true;
    }

    /// <summary>Where a ship is: as the client sees it when it is in view, else where the server last listed it.</summary>
    private (MapId Map, Vector2 Position) Locate(NetEntity grid, MapId listedMap, Vector2 listedPosition)
    {
        if (_entMan.TryGetEntity(grid, out var uid)
            && _entMan.TryGetComponent(uid, out TransformComponent? xform)
            && xform.MapID != MapId.Nullspace)
            return (xform.MapID, Xforms.GetWorldPosition(xform));

        return (listedMap, listedPosition);
    }

    /// <summary>One row of the list with the controls the compass keeps up to date.</summary>
    private sealed class ShipRow(WGShipAdminRow ship, WGShipAdminCompass compass, Label distance)
    {
        public readonly WGShipAdminRow Ship = ship;
        public readonly WGShipAdminCompass Compass = compass;
        public readonly Label Distance = distance;
        public int Shown = Unset;
    }
}
