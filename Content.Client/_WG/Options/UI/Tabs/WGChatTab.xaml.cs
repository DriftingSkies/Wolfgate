using Content.Shared._WG.HideTyping;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WG.Options.UI.Tabs;

/// <summary>The Wolfgate Chat tab: chat log and text, speech bubbles and notifications.</summary>
[GenerateTypedNameReferences]
public sealed partial class WGChatTab : Control
{
    public WGChatTab()
    {
        RobustXamlLoader.Load(this);

        Control.AddOptionCheckBox(CCVars.LogInChat, LogInChatCheckBox);
        Control.AddOptionCheckBox(CCVars.CoalesceIdenticalMessages, CoalesceIdenticalMessagesCheckBox);
        Control.AddOptionCheckBox(HideTypingCVars.ShowMyTyping, ShowMyTypingCheckBox);
        WgAddChatTextSizeOptions();
        WgAddSpeechBubbleOptions();
        WgAddNotificationOptions();

        Control.Initialize();
    }
}
