using Content.Client.Audio;
using Content.Shared._Mono.CCVar;
using Content.Shared._WG.CCVar;
using Content.Shared._WG.ShipPa;
using Content.Shared._WG.Voice;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WG.Options.UI.Tabs;

/// <summary>The Wolfgate Audio tab: voice, PA and jukebox volumes, combat music and area echo.</summary>
[GenerateTypedNameReferences]
public sealed partial class WGAudioTab : Control
{
    public WGAudioTab()
    {
        RobustXamlLoader.Load(this);

        Control.AddOptionPercentSlider(SpeechVoiceCVars.Volume, SliderVolumeVoices, max: SpeechVoiceCVars.MaxVolume);
        Control.AddOptionPercentSlider(ShipPaCVars.Volume, SliderVolumeShipPa, min: ShipPaCVars.MinVolume);
        Control.AddOptionPercentSlider(InternetSoundCVars.Volume, InternetSoundVolumeSlider);
        Control.AddOptionPercentSlider(JukeboxVolumeCVars.Volume, JukeboxVolumeSlider);
        Control.AddOptionCheckBox(SpeechVoiceCVars.Enabled, SpeechVoicesCheckBox);
        Control.AddOptionCheckBox(SoundtrackMuteCVars.Enabled, SoundtrackMuteCheckBox);
        Control.AddOptionCheckBox(MonoCVars.RadioNoiseEnabled, RadioNoiseCheckBox);

        Control.AddOptionCheckBox(MonoCVars.CombatMusicEnabled, CombatMusicCheckBox);
        Control.AddOptionPercentSlider(
            MonoCVars.CombatMusicVolume,
            SliderVolumeCombatMusic,
            scale: ContentAudioSystem.CombatMultiplier);
        Control.AddOptionSlider(
            MonoCVars.CombatMusicWindUpTime,
            SliderWindUpCombatMusic,
            1,
            10,
            (_, value) => Loc.GetString("ui-options-combat-music-sec-format", ("value", value)));
        Control.AddOptionSlider(
            MonoCVars.CombatMusicWindDownTime,
            SliderWindDownCombatMusic,
            1,
            120,
            (_, value) => Loc.GetString("ui-options-combat-music-sec-format", ("value", value)));

        Control.AddOptionCheckBox(MonoCVars.AreaEchoEnabled, AreaEchoCheckBox);
        Control.AddOptionCheckBox(MonoCVars.AreaEchoHighResolution, AreaEchoHighResolutionCheckBox);

        Control.Initialize();
    }
}
