using Content.Shared._DV.CCVars;
using Content.Shared._WG.DarkFlash;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WG.Options.UI.Tabs;

/// <summary>The Wolfgate Accessibility tab: flash darkening and species vision filters.</summary>
[GenerateTypedNameReferences]
public sealed partial class WGAccessibilityTab : Control
{
    public WGAccessibilityTab()
    {
        RobustXamlLoader.Load(this);

        Control.AddOptionCheckBox(DarkFlashCVars.Enabled, DarkFlashCheckBox);
        Control.AddOptionCheckBox(DCCVars.NoVisionFilters, DisableFiltersCheckBox);

        Control.Initialize();
    }
}
