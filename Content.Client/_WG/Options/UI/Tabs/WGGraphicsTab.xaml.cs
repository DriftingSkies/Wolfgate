using Content.Client.Options.UI;
using Content.Shared._FarHorizons.CCVar;
using Content.Shared._WG.CCVar;
using Content.Shared._WG.InteractionParticles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WG.Options.UI.Tabs;

/// <summary>The Wolfgate Graphics tab: frame cap, extra visual detail and screen distortion effects.</summary>
[GenerateTypedNameReferences]
public sealed partial class WGGraphicsTab : Control
{
    public WGGraphicsTab()
    {
        RobustXamlLoader.Load(this);

        WgAddDisplayOptions();
        Control.AddOptionDropDown(
            InteractionParticleCVars.Mode,
            DropDownInteractionParticles,
            new List<OptionDropDownCVar<int>.ValueOption>
            {
                new((int) InteractionParticleMode.All, Loc.GetString("ui-options-interaction-particles-all")),
                new((int) InteractionParticleMode.WithoutInHand, Loc.GetString("ui-options-interaction-particles-without-inhand")),
                new((int) InteractionParticleMode.None, Loc.GetString("ui-options-interaction-particles-none")),
            });
        WgAddWeatherQuality();
        Control.AddOptionCheckBox(FHCCVars.RenderStarSystem, RenderStarSystemCheckBox);

        Control.AddOptionCheckBox(HeatHazeCVars.Enabled, HeatHazeCheckBox);
        Control.AddOptionPercentSlider(HeatHazeCVars.Strength, HeatHazeStrengthSlider, 0, 2);
        Control.AddOptionCheckBox(ShockwaveCVars.Enabled, ShockwaveCheckBox);
        Control.AddOptionPercentSlider(ShockwaveCVars.Strength, ShockwaveStrengthSlider, 0, 2);

        Control.Initialize();
    }
}
