using Content.Client.Options.UI.Tabs;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WG.Options.UI;

/// <summary>The sub-tabs of the Wolfgate side of the options window: every setting stock SS14 doesn't have.</summary>
[GenerateTypedNameReferences]
public sealed partial class WolfgateOptionsTabs : TabContainer
{
    /// <summary>Index of the Controls tab, the fork-only keybind list.</summary>
    public const int ControlsTabIndex = 5;

    /// <summary>The fork-only keybind list.</summary>
    public readonly KeyRebindTab ControlsTab = new(true);

    public WolfgateOptionsTabs()
    {
        RobustXamlLoader.Load(this);

        AddChild(ControlsTab);
        ControlsTab.SetPositionInParent(ControlsTabIndex);

        SetTabTitle(0, Loc.GetString("wg-options-tab-interface"));
        SetTabTitle(1, Loc.GetString("wg-options-tab-chat"));
        SetTabTitle(2, Loc.GetString("ui-options-tab-graphics"));
        SetTabTitle(3, Loc.GetString("ui-options-tab-audio"));
        SetTabTitle(4, Loc.GetString("ui-options-tab-accessibility"));
        SetTabTitle(ControlsTabIndex, Loc.GetString("ui-options-tab-controls"));
        SetTabTitle(ConsentTab, Loc.GetString("ui-options-tab-consent"));
    }

    /// <summary>Reloads every tab from the current cvars and consent state.</summary>
    public void ReloadValues()
    {
        InterfaceTab.Control.ReloadValues();
        ChatTab.Control.ReloadValues();
        GraphicsTab.Control.ReloadValues();
        AudioTab.Control.ReloadValues();
        AccessibilityTab.Control.ReloadValues();
        ConsentTab.Refresh();
    }
}
