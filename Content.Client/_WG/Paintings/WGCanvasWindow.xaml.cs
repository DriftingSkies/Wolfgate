using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._WG.Paintings;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Timing;

namespace Content.Client._WG.Paintings;

/// <summary>The paint tool a painter holds, as the canvas window shows it.</summary>
public readonly record struct WGPaintTool(
    Color Colour,
    bool Palette,
    IReadOnlyList<Color> Swatches,
    IReadOnlyList<Color> Recent);

/// <summary>Paints a canvas: the pixels, the held tool's colour and palette, and finishing under a title.</summary>
[GenerateTypedNameReferences]
public sealed partial class WGCanvasWindow : FancyWindow
{
    /// <summary>How often strokes are sent.</summary>
    private const float SendInterval = 0.1f;

    private static readonly Color BackdropColour = Color.FromHex("#1a1a1e");
    private static readonly Color SwatchBorder = Color.FromHex("#3a3a42");
    private static readonly Color SelectedBorder = Color.FromHex("#f2f2f2");

    public event Action<ushort[], bool>? OnPaint;
    public event Action<Color>? OnPickColor;
    public event Action<Color, bool>? OnSwatch;
    public event Action<string, bool>? OnFinish;

    /// <summary>Reads the paint tool the player holds, or null when they hold none.</summary>
    public Func<WGPaintTool?>? GetTool;

    private readonly StyleBoxFlat _brushStyle = new() { BorderThickness = new Thickness(2), BorderColor = SwatchBorder };

    /// <summary>The swatches shown, so the one matching the brush can be outlined.</summary>
    private readonly List<(Color Colour, StyleBoxFlat Style)> _swatchStyles = new();

    private readonly List<Color> _shownSwatches = new();
    private readonly List<Color> _shownRecent = new();

    /// <summary>A palette colour picked here and not yet sent; it goes with the next stroke.</summary>
    private Color? _pending;

    private WGPaintTool? _tool;
    private bool _settingSliders;
    private float _sinceSent;

    public WGCanvasWindow()
    {
        RobustXamlLoader.Load(this);
        Backdrop.PanelOverride = new StyleBoxFlat { BackgroundColor = BackdropColour };
        BrushSwatch.PanelOverride = _brushStyle;

        PencilButton.OnPressed += _ => SetMode(WGCanvasControl.Tool.Pencil);
        FillButton.OnPressed += _ => SetMode(WGCanvasControl.Tool.Fill);
        PickerButton.OnPressed += _ => SetMode(WGCanvasControl.Tool.Picker);
        PencilButton.Pressed = true;
        GridCheck.OnToggled += args => CanvasView.ShowGrid = args.Pressed;

        Sliders.OnColorChanged += colour =>
        {
            if (!_settingSliders)
                Pick(colour);
        };
        CanvasView.ColourPicked += colour =>
        {
            Pick(colour);
            SetSliders(colour);
        };
        SaveColourButton.OnPressed += _ =>
        {
            if (CanvasView.Brush is { } brush)
                OnSwatch?.Invoke(brush, false);
        };

        TitleEdit.IsValid = text => text.Length <= WGPaintingRules.MaxTitleLength;
        FinishButton.OnPressed += _ =>
        {
            Send();
            OnFinish?.Invoke(TitleEdit.Text, AnonymousCheck.Pressed);
        };
    }

    private void SetMode(WGCanvasControl.Tool mode)
    {
        CanvasView.Mode = mode;
        PencilButton.Pressed = mode == WGCanvasControl.Tool.Pencil;
        FillButton.Pressed = mode == WGCanvasControl.Tool.Fill;
        PickerButton.Pressed = mode == WGCanvasControl.Tool.Picker;
    }

    public void UpdateState(WGCanvasUiState state)
    {
        CanvasView.Locked = state.Finished;
        CanvasView.SetPixels(state.Width, state.Height, state.Pixels);
        SidePanel.Visible = !state.Finished;
        FinishPanel.Visible = !state.Finished;
        Signature.Visible = state.Finished;
        Signature.Text = Loc.GetString("wg-canvas-signature", ("title", state.Title), ("artist", state.Artist));
        UpdateTool();
    }

    /// <summary>Takes up a palette colour; strokes painted before it are sent first, in the old colour.</summary>
    private void Pick(Color colour)
    {
        if (_tool is not { Palette: true })
            return;

        Send();
        _pending = colour.WithAlpha(1f);
        UpdateTool();
    }

    private void SetSliders(Color colour)
    {
        _settingSliders = true;
        Sliders.Color = colour;
        _settingSliders = false;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateTool();
        _sinceSent += args.DeltaSeconds;
        if (_sinceSent >= SendInterval)
            Send();
    }

    /// <summary>Shows the held tool, and drops a pending colour once the palette has it.</summary>
    private void UpdateTool()
    {
        var tool = GetTool?.Invoke();
        var paletteChanged = tool?.Palette != _tool?.Palette
            || tool is { } now && (now.Colour != _tool?.Colour
                || !now.Swatches.SequenceEqual(_shownSwatches)
                || !now.Recent.SequenceEqual(_shownRecent));
        _tool = tool;

        if (tool is not { Palette: true })
            _pending = null;
        else if (_pending is { } pending && WGPaintingRules.Quantize(pending) == tool.Value.Colour)
            _pending = null;

        var brush = _pending ?? tool?.Colour;
        CanvasView.Brush = brush;
        _brushStyle.BackgroundColor = brush ?? Color.Transparent;
        BrushHex.Text = brush is { } shown ? shown.ToHexNoAlpha().ToUpperInvariant() : string.Empty;
        ToolLabel.Text = Loc.GetString(tool == null ? "wg-canvas-no-tool-held"
            : tool.Value.Palette ? "wg-canvas-palette-held"
            : "wg-canvas-crayon-held");

        PickerButton.Disabled = tool is not { Palette: true };
        if (PickerButton.Disabled && CanvasView.Mode == WGCanvasControl.Tool.Picker)
            SetMode(WGCanvasControl.Tool.Pencil);

        PalettePanel.Visible = tool is { Palette: true };
        if (tool is not { Palette: true } palette)
            return;

        if (paletteChanged)
            ShowPalette(palette);

        var current = brush is { } colour ? WGPaintingRules.Quantize(colour) : (Color?) null;
        foreach (var (swatch, style) in _swatchStyles)
            style.BorderColor = swatch == current ? SelectedBorder : SwatchBorder;

        var saved = current is { } c && palette.Swatches.Contains(c);
        SaveColourButton.Disabled = current == null || saved || palette.Swatches.Count >= WGPaintingRules.MaxSwatches;
    }

    private void ShowPalette(WGPaintTool palette)
    {
        if (_pending == null)
            SetSliders(palette.Colour);

        _shownSwatches.Clear();
        _shownSwatches.AddRange(palette.Swatches);
        _shownRecent.Clear();
        _shownRecent.AddRange(palette.Recent);
        _swatchStyles.Clear();

        SavedSwatches.RemoveAllChildren();
        foreach (var colour in palette.Swatches)
            SavedSwatches.AddChild(Swatch(colour, true));
        PaletteEmpty.Visible = palette.Swatches.Count == 0;
        PaletteCount.Text = Loc.GetString("wg-canvas-palette-count",
            ("count", palette.Swatches.Count), ("max", WGPaintingRules.MaxSwatches));

        RecentSwatches.RemoveAllChildren();
        foreach (var colour in palette.Recent)
            RecentSwatches.AddChild(Swatch(colour, false));
    }

    /// <summary>A colour to pick with a left click; a saved one is removed with a right click.</summary>
    private ContainerButton Swatch(Color colour, bool saved)
    {
        var hex = colour.ToHexNoAlpha().ToUpperInvariant();
        var button = new ContainerButton
        {
            MinSize = new Vector2(32, 32),
            EnableAllKeybinds = saved,
            ToolTip = saved ? Loc.GetString("wg-canvas-swatch-saved-tooltip", ("hex", hex)) : hex,
        };
        var style = new StyleBoxFlat { BackgroundColor = colour, BorderColor = SwatchBorder, BorderThickness = new Thickness(2) };
        _swatchStyles.Add((colour, style));
        button.AddChild(new PanelContainer { PanelOverride = style });
        button.OnPressed += args =>
        {
            if (args.Event.Function == EngineKeyFunctions.UIRightClick)
            {
                OnSwatch?.Invoke(colour, true);
                return;
            }

            if (args.Event.Function != EngineKeyFunctions.UIClick)
                return;

            Pick(colour);
            SetSliders(colour);
        };
        return button;
    }

    /// <summary>Sends a pending palette colour, then the strokes painted since the last send.</summary>
    private void Send()
    {
        _sinceSent = 0;
        if (CanvasView.Painted.Count == 0 && CanvasView.Erased.Count == 0)
            return;

        if (_pending is { } colour && CanvasView.Painted.Count > 0)
            OnPickColor?.Invoke(colour);
        CanvasView.MarkSent();
        SendChunks(CanvasView.Painted, false);
        SendChunks(CanvasView.Erased, true);
    }

    private void SendChunks(HashSet<ushort> pixels, bool erase)
    {
        if (pixels.Count == 0)
            return;

        var all = new ushort[pixels.Count];
        pixels.CopyTo(all);
        pixels.Clear();
        for (var i = 0; i < all.Length; i += WGPaintingRules.MaxStrokePixels)
        {
            var chunk = new ushort[Math.Min(WGPaintingRules.MaxStrokePixels, all.Length - i)];
            Array.Copy(all, i, chunk, 0, chunk.Length);
            OnPaint?.Invoke(chunk, erase);
        }
    }
}
