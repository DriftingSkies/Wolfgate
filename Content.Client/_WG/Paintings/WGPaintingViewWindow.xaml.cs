using Content.Client.UserInterface.Controls;
using Content.Shared._WG.Paintings;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WG.Paintings;

/// <summary>A closer look at a framed painting.</summary>
[GenerateTypedNameReferences]
public sealed partial class WGPaintingViewWindow : FancyWindow
{
    public WGPaintingViewWindow()
    {
        RobustXamlLoader.Load(this);
        Wall.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#1a1a1e") };
    }

    public void UpdateState(WGCanvasUiState state)
    {
        PaintingView.SetPixels(state.Width, state.Height, state.Pixels);
        PaintingTitle.Text = Loc.GetString("wg-painting-view-name", ("title", state.Title));
        PaintingArtist.Text = Loc.GetString("wg-painting-view-artist", ("artist", state.Artist));
    }
}
