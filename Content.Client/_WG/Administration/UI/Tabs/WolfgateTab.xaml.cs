using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._WG.Administration.UI.Tabs;

/// <summary>
/// Admin menu tab that holds the Wolfgate admin tooling.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WolfgateTab : Control
{
    public WolfgateTab()
    {
        RobustXamlLoader.Load(this);
    }

    protected override void VisibilityChanged(bool newVisible)
    {
        base.VisibilityChanged(newVisible);
        if (newVisible)
            GrowWindow();
    }

    /// <summary>
    /// Makes the admin menu big enough for this tab. The menu takes its size from the tab it opens on and only
    /// measures the tab that is showing, so a tab with more rows than the first is cut off without this.
    /// </summary>
    private void GrowWindow()
    {
        Control? parent = Parent;
        while (parent != null && parent is not BaseWindow)
            parent = parent.Parent;

        if (parent is not BaseWindow window)
            return;

        window.Measure(Vector2Helpers.Infinity);
        var wanted = Vector2.Max(window.Size, window.DesiredSize);
        if (wanted != window.Size)
            window.SetSize = wanted;
    }
}
