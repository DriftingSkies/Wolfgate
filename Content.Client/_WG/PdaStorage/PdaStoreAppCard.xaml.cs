using Robust.Client.AutoGenerated;
using Content.Client.Message;
using Content.Client._WG.PdaUi;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Client._WG.PdaStorage;

/// <summary>
/// One store listing in the Wolfgate Retro card style: icon and name, size, download action (or an inline
/// percentage box while downloading), and the description underneath.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaStoreAppCard : PanelContainer
{
    [Dependency] private IResourceCache _resCache = default!;

    public string AppId = string.Empty;
    public PdaButton Button => DownloadButton;

    /// <summary>Whether the card is currently showing its inline download percentage box.</summary>
    public bool ShowingProgress => TaskProgress.Visible;

    public PdaStoreAppCard()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var panel = PdaPalette.PanelTexture(_resCache, "panel_bordered.png", 3);
        panel.SetContentMarginOverride(StyleBox.Margin.All, 3);
        PanelOverride = panel;
        NameLabel.FontOverride = PdaPalette.Mono(_resCache, 11);
        NameLabel.FontColorOverride = PdaPalette.Text;
        SizeLabel.FontOverride = PdaPalette.Mono(_resCache, 10);
        SizeLabel.FontColorOverride = PdaPalette.TextMuted;
        DescriptionLabel.ModulateSelfOverride = PdaPalette.TextMuted;
    }

    public SpriteSpecifier? Icon
    {
        set
        {
            if (value is not { } icon)
            {
                IconRect.Visible = false;
                NameLabel.Margin = new Thickness(0);
                return;
            }

            IconRect.Visible = true;
            PdaIcons.Apply(IconRect, icon, 16);
            NameLabel.Margin = new Thickness(6, 0, 0, 0);
        }
    }

    public void SetContent(string name, string description, string size, string? actionText, bool actionEnabled)
    {
        NameLabel.Text = name;
        SizeLabel.Text = size;

        DescriptionLabel.SetMarkup(description);
        DescriptionLabel.Visible = !string.IsNullOrEmpty(description);

        DownloadButton.Text = actionText ?? string.Empty;
        DownloadButton.Visible = actionText != null;
        DownloadButton.Disabled = !actionEnabled;

        TaskProgress.Visible = false;
    }

    /// <summary>Replaces the download button with a percentage box while this app is downloading.</summary>
    public void ShowProgress(float? fraction, string? text)
    {
        var downloading = fraction.HasValue;
        TaskProgress.Visible = downloading;

        if (!downloading)
        {
            DownloadButton.Visible = !string.IsNullOrEmpty(DownloadButton.Text);
            return;
        }

        DownloadButton.Visible = false;
        TaskProgress.Text = text;
        TaskProgress.SetProgress(fraction!.Value, 1f);
    }
}
