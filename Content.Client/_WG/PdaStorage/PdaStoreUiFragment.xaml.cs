using System.Linq;
using Content.Client._WG.PdaUi;
using Content.Shared._WG.PdaStorage;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.Maths;

namespace Content.Client._WG.PdaStorage;

/// <summary>
/// Store and storage screen in the Wolfgate layout: capacity bar and search on top, category sidebar,
/// application cards with inline download progress, and a storage tab for removal and disk copies.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PdaStoreUiFragment : BoxContainer
{
    public event Action<PdaStoreAction, string, NetEntity>? OnAction;

    /// <summary>Replaces the action sink when the same live fragment is reused by a new interface.</summary>
    public void SetActionHandler(Action<PdaStoreAction, string, NetEntity>? handler)
    {
        OnAction = handler;
    }

    private readonly List<(PdaStoreAppEntry Entry, PdaStoreAppCard Card)> _appCards = new();
    private readonly List<PdaIconButton> _categoryButtons = new();

    private PdaIconButton _storeTab = default!;
    private PdaIconButton _storageTab = default!;

    private string _category = string.Empty;
    private string _search = string.Empty;
    private string _appSignature = string.Empty;
    private string _storageSignature = string.Empty;

    public PdaStoreUiFragment()
    {
        RobustXamlLoader.Load(this);

        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;

        BuildTabs();
        BuildChrome();
        SelectTab(false);
    }

    private void BuildChrome()
    {
        ErrorLabel.FontColorOverride = PdaPalette.Bad;
        NoAppsLabel.FontColorOverride = PdaPalette.TextMuted;
        NothingInstalledLabel.FontColorOverride = PdaPalette.TextMuted;

        Search.OnTextChanged += args =>
        {
            _search = args.Text;
            ApplyFilter();
        };

        var refresh = new PdaButton { Text = Loc.GetString("pda-store-refresh") };
        refresh.OnPressed += _ => OnAction?.Invoke(PdaStoreAction.RequestState, string.Empty, NetEntity.Invalid);
        StorageHeader.Buttons.AddChild(refresh);
    }

    private void BuildTabs()
    {
        _storeTab = new PdaIconButton
        {
            LabelText = Loc.GetString("pda-store-title-store"),
            MinHeight = 24,
        };
        _storeTab.SetIcon(PdaIcons.Program, 13);
        _storeTab.OnPressed += _ => SelectTab(false);
        TabBar.AddChild(_storeTab);

        _storageTab = new PdaIconButton
        {
            LabelText = Loc.GetString("pda-store-title-storage"),
            MinHeight = 24,
        };
        _storageTab.SetIcon(PdaIcons.Disk, 13);
        _storageTab.OnPressed += _ => SelectTab(true);
        TabBar.AddChild(_storageTab);
    }

    private void SelectTab(bool storage)
    {
        StoreView.Visible = !storage;
        StorageView.Visible = storage;
        _storeTab.IsCurrent = !storage;
        _storageTab.IsCurrent = storage;

        // Slots can change while the screen is open; ask for a fresh snapshot on tab change.
        if (IsInsideTree)
            OnAction?.Invoke(PdaStoreAction.RequestState, string.Empty, NetEntity.Invalid);
    }

    public void UpdateState(PdaStoreUiState state)
    {
        CapacityBar.Text = Loc.GetString("pda-store-free-of",
            ("free", state.Capacity - state.Used), ("capacity", state.Capacity));
        CapacityBar.SetProgress(state.Used, state.Capacity);

        StorageCapacityRow.SetValue(Loc.GetString("pda-store-capacity",
            ("used", state.Used), ("capacity", state.Capacity)));

        UpdateError(state.Error);
        UpdateMedia(state);
        UpdateDisk(state);

        var appSignature = string.Join('|', state.Apps.Select(app =>
            $"{app.Id}:{app.Installed}:{app.Compatible}:{app.HasAccess}:{app.Size}"));

        if (appSignature != _appSignature)
        {
            _appSignature = appSignature;
            RebuildApps(state);
        }

        UpdateDownload(state);

        var storageSignature = string.Join('|',
            state.Installed.Select(program => $"{program.Program}:{program.Readonly}:{program.Running}:{program.Size}"))
            + "|" + string.Join('|',
                state.Cartridge.Select(program => $"{program.Program}:{program.AppId}:{program.Size}"))
            + "|" + state.DiskCapacity + ":" + state.DiskUsed + ":"
            + string.Join('|', state.Disk.Select(program => $"{program.Program}:{program.Size}"));

        if (storageSignature != _storageSignature)
        {
            _storageSignature = storageSignature;
            RebuildInstalled(state);
            RebuildCartridge(state);
            RebuildDisk(state);
        }
    }

    private void UpdateDownload(PdaStoreUiState state)
    {
        foreach (var (entry, card) in _appCards)
        {
            if (!entry.Installed && entry.Compatible && entry.HasAccess)
                card.Button.Disabled = state.Downloading;

            if (!state.Downloading || entry.Id != state.DownloadAppId)
            {
                card.ShowProgress(null, null);
                continue;
            }

            var fraction = state.DownloadSize <= 0
                ? 1f
                : Math.Clamp(state.DownloadProgress / state.DownloadSize, 0f, 1f);

            var percent = (int) MathF.Floor(fraction * 100f);
            card.ShowProgress(fraction, Loc.GetString("pda-store-download-percent", ("percent", percent)));
        }
    }

    private void UpdateError(PdaStoreError error)
    {
        ErrorLabel.Visible = error != PdaStoreError.None;
        if (error != PdaStoreError.None)
            ErrorLabel.Text = Loc.GetString(ErrorKey(error));
    }

    private void UpdateMedia(PdaStoreUiState state)
    {
        MediaRow.Visible = state.Cartridge.Count > 0;
        if (state.Cartridge.Count == 0)
            return;

        var media = state.Cartridge[0];
        MediaRow.SetValue(Loc.GetString("pda-store-cartridge", ("name", Loc.GetString(media.Name))));
    }

    private void UpdateDisk(PdaStoreUiState state)
    {
        DiskSection.Visible = state.DiskCapacity > 0;
        if (state.DiskCapacity > 0)
        {
            DiskCapacityRow.SetValue(Loc.GetString("pda-store-capacity",
                ("used", state.DiskUsed), ("capacity", state.DiskCapacity)));
        }
    }

    private void RebuildApps(PdaStoreUiState state)
    {
        AppList.RemoveAllChildren();
        _appCards.Clear();

        foreach (var app in state.Apps)
        {
            var card = new PdaStoreAppCard
            {
                AppId = app.Id,
                Icon = PdaProgramIcons.Get(app.Name) ?? app.Icon,
            };

            string? action;
            var enabled = false;

            if (app.Installed)
            {
                action = Loc.GetString("pda-store-installed");
            }
            else if (!app.Compatible)
            {
                action = Loc.GetString("pda-store-incompatible");
            }
            else if (!app.HasAccess)
            {
                action = Loc.GetString("pda-store-no-access");
            }
            else
            {
                action = Loc.GetString("pda-store-download");
                enabled = true;
            }

            card.SetContent(
                Loc.GetString(app.Name),
                Loc.GetString(app.Description),
                Loc.GetString("pda-store-size", ("size", app.Size)),
                action,
                enabled);

            if (enabled)
            {
                var id = app.Id;
                card.Button.OnPressed += _ => OnAction?.Invoke(PdaStoreAction.Install, id, NetEntity.Invalid);
            }

            AppList.AddChild(card);
            _appCards.Add((app, card));
        }

        RebuildCategories(state);
        ApplyFilter();
    }

    private void RebuildCategories(PdaStoreUiState state)
    {
        var categories = state.Apps
            .Select(app => (app.Category, app.CategoryName))
            .Distinct()
            .ToList();

        if (CategoryBar.ChildCount == categories.Count + 1)
            return;

        CategoryBar.RemoveAllChildren();
        _categoryButtons.Clear();

        AddCategoryButton(string.Empty, Loc.GetString("pda-store-category-all"));

        foreach (var (id, name) in categories)
            AddCategoryButton(id, string.IsNullOrEmpty(name) ? id : Loc.GetString(name));
    }

    private void AddCategoryButton(string category, string label)
    {
        var button = new PdaIconButton
        {
            LabelText = label,
            MinHeight = 26,
            HorizontalExpand = true,
            IsCurrent = category == _category,
        };

        button.OnPressed += _ =>
        {
            _category = category;
            foreach (var other in _categoryButtons)
                other.IsCurrent = false;
            button.IsCurrent = true;
            ApplyFilter();
        };

        CategoryBar.AddChild(button);
        _categoryButtons.Add(button);
    }

    private void ApplyFilter()
    {
        var any = false;

        foreach (var (entry, card) in _appCards)
        {
            var visible = (string.IsNullOrEmpty(_category) || entry.Category == _category)
                && (string.IsNullOrEmpty(_search)
                    || Loc.GetString(entry.Name).Contains(_search, StringComparison.OrdinalIgnoreCase));

            card.Visible = visible;
            any |= visible;
        }

        NoAppsLabel.Visible = !any;
        NoAppsLabel.Text = Loc.GetString("pda-store-no-apps");
    }

    private void RebuildInstalled(PdaStoreUiState state)
    {
        InstalledList.RemoveAllChildren();

        foreach (var program in state.Installed)
        {
            var status = program.Running
                ? Loc.GetString("pda-store-running")
                : program.Readonly
                    ? Loc.GetString("pda-store-system")
                    : Loc.GetString("pda-store-size", ("size", program.Size));

            var row = new PdaProgramRow
            {
                ProgramName = Loc.GetString(program.Name),
                Icon = PdaProgramIcons.Get(program.Name),
                Status = status,
                StatusColor = program.Running ? PdaPalette.Accent : PdaPalette.TextMuted,
            };

            if (!program.Readonly)
            {
                row.Action.Visible = true;
                row.Action.Text = Loc.GetString("pda-store-remove");
                var target = program.Program;
                row.Action.OnPressed += _ => OnAction?.Invoke(PdaStoreAction.Uninstall, string.Empty, target);
            }

            if (state.DiskCapacity > 0)
            {
                row.AltAction.Visible = true;
                row.AltAction.Text = Loc.GetString("pda-store-copy-to-disk");
                var target = program.Program;
                row.AltAction.OnPressed += _ => OnAction?.Invoke(PdaStoreAction.CopyToDisk, string.Empty, target);
            }

            InstalledList.AddChild(row);
        }

        NothingInstalledLabel.Visible = state.Installed.Count == 0;
        NothingInstalledLabel.Text = Loc.GetString("pda-store-empty");
    }

    private void RebuildCartridge(PdaStoreUiState state)
    {
        if (state.Cartridge.Count == 0)
            return;

        var media = state.Cartridge[0];
        if (state.Installed.Any(program => program.AppId == media.AppId && media.AppId != string.Empty))
            return;

        var row = new PdaProgramRow
        {
            ProgramName = Loc.GetString(media.Name),
            Icon = PdaProgramIcons.Get(media.Name),
            Status = Loc.GetString("pda-store-size", ("size", media.Size)),
            StatusColor = PdaPalette.TextMuted,
        };

        row.Action.Visible = true;
        row.Action.Text = Loc.GetString("pda-store-install");
        var target = media.Program;
        row.Action.OnPressed += _ => OnAction?.Invoke(PdaStoreAction.InstallFromMedia, string.Empty, target);
        InstalledList.AddChild(row);
    }

    private void RebuildDisk(PdaStoreUiState state)
    {
        DiskList.RemoveAllChildren();

        foreach (var program in state.Disk)
        {
            var row = new PdaProgramRow
            {
                ProgramName = Loc.GetString(program.Name),
                Icon = PdaProgramIcons.Get(program.Name),
                Status = Loc.GetString("pda-store-size", ("size", program.Size)),
                StatusColor = PdaPalette.TextMuted,
            };

            row.Action.Visible = true;
            row.Action.Text = Loc.GetString("pda-store-copy-from-disk");
            var target = program.Program;
            row.Action.OnPressed += _ => OnAction?.Invoke(PdaStoreAction.CopyFromDisk, string.Empty, target);

            DiskList.AddChild(row);
        }

        DiskEmptyLabel.Visible = state.Disk.Count == 0;
        DiskEmptyLabel.Text = Loc.GetString("pda-store-disk-empty");
    }

    private static string ErrorKey(PdaStoreError error)
    {
        return error switch
        {
            PdaStoreError.UnknownApp => "pda-store-error-unknownapp",
            PdaStoreError.Unavailable => "pda-store-error-unavailable",
            PdaStoreError.Incompatible => "pda-store-error-incompatible",
            PdaStoreError.NoAccess => "pda-store-error-noaccess",
            PdaStoreError.AlreadyInstalled => "pda-store-error-alreadyinstalled",
            PdaStoreError.NoSpace => "pda-store-error-nospace",
            PdaStoreError.AlreadyDownloading => "pda-store-error-alreadydownloading",
            PdaStoreError.InstallFailed => "pda-store-error-installfailed",
            PdaStoreError.NotInstalled => "pda-store-error-notinstalled",
            PdaStoreError.Readonly => "pda-store-error-readonly",
            PdaStoreError.NoDisk => "pda-store-error-nodisk",
            PdaStoreError.DiskFull => "pda-store-error-diskfull",
            PdaStoreError.InvalidMedia => "pda-store-error-invalidmedia",
            _ => "pda-store-error-installfailed",
        };
    }
}
