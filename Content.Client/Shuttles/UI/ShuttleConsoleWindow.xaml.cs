using System.Numerics;
using Content.Client.Computer;
using Content.Client.UserInterface.Controls;
using Content.Shared.Shuttles.BUIStates;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Map;

namespace Content.Client.Shuttles.UI;

[GenerateTypedNameReferences]
public sealed partial class ShuttleConsoleWindow : FancyWindow,
    IComputerWindow<ShuttleBoundUserInterfaceState>
{
    [Dependency] private IEntityManager _entManager = default!;

    private ShuttleConsoleMode _mode = ShuttleConsoleMode.Nav;

    public event Action<MapCoordinates, Angle>? RequestFTL;
    public event Action<NetEntity, Angle>? RequestBeaconFTL;

    // Mono
    public event Action<MapCoordinates, Angle>? RequestAutopilot;

    public event Action<NetEntity, NetEntity>? DockRequest;
    public event Action<NetEntity>? UndockRequest;
    public event Action<List<NetEntity>>? UndockAllRequest;
    public event Action<List<NetEntity>, bool>? ToggleFTLLockRequest;

    public ShuttleConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        // Mode switching
        NavModeButton.OnPressed += NavPressed;
        ShipModeButton.OnPressed += ShipPressed; // WOLFGATE(Shuttles)
        AccessModeButton.OnPressed += AccessPressed; // WOLFGATE(ShipAccess)
        MapModeButton.OnPressed += MapPressed;
        DockModeButton.OnPressed += DockPressed;

        // Modes are exclusive
        var group = new ButtonGroup();

        NavModeButton.Group = group;
        ShipModeButton.Group = group; // WOLFGATE(Shuttles)
        AccessModeButton.Group = group; // WOLFGATE(ShipAccess)
        MapModeButton.Group = group;
        DockModeButton.Group = group;

        NavModeButton.Pressed = true;
        SetupMode(_mode);

        MapContainer.RequestFTL += (coords, angle) =>
        {
            RequestFTL?.Invoke(coords, angle);
        };

        MapContainer.RequestBeaconFTL += (ent, angle) =>
        {
            RequestBeaconFTL?.Invoke(ent, angle);
        };

        // Mono
        MapContainer.RequestAutopilot += (coords, angle) =>
        {
            RequestAutopilot?.Invoke(coords, angle);
        };

        DockContainer.DockRequest += (entity, netEntity) =>
        {
            DockRequest?.Invoke(entity, netEntity);
        };

        DockContainer.UndockRequest += entity =>
        {
            UndockRequest?.Invoke(entity);
        };

        DockContainer.UndockAllRequest += dockEntities =>
        {
            UndockAllRequest?.Invoke(dockEntities);
        };

        DockContainer.ToggleFTLLockRequest += (dockEntities, enabled) =>
        {
            ToggleFTLLockRequest?.Invoke(dockEntities, enabled);
        };

        NfInitialize(); // Frontier Initialization for the ShuttleConsoleWindow
        WfInitialize(); // WOLFGATE(Shuttles)
        WfAccessInitialize(); // WOLFGATE(ShipAccess)
        WfShieldInitialize(); // WOLFGATE(ShipShields): add the shield allocation tab.
        WfSectorInitialize(); // WOLFGATE(SectorControl): wire up the sector map mode button.
    }

    private void ClearModes(ShuttleConsoleMode mode)
    {
        // WOLFGATE(ShipShields) START: hide shield allocation outside its helm tab.
        if (mode != ShuttleConsoleMode.Shields)
            _shieldScreen.Visible = false;
        // WOLFGATE END
        if (mode != ShuttleConsoleMode.Nav)
        {
            NavContainer.Visible = false;
        }

        // WOLFGATE(Shuttles) START: ship mode
        if (mode != ShuttleConsoleMode.Ship)
        {
            WfSetShipMode(false);
        }
        // WOLFGATE END

        // WOLFGATE(ShipAccess) START: access tab
        if (mode != ShuttleConsoleMode.Access)
        {
            WfSetAccessMode(false);
        }
        // WOLFGATE END

        // WOLFGATE(SectorControl) START: hide the sector map in other modes
        if (mode != ShuttleConsoleMode.Sector)
        {
            WfSetSectorMode(false);
        }
        // WOLFGATE END

        if (mode != ShuttleConsoleMode.Map)
        {
            MapContainer.Visible = false;
            MapContainer.SetMap(MapId.Nullspace, Vector2.Zero);
        }

        if (mode != ShuttleConsoleMode.Dock)
        {
            DockContainer.Visible = false;
        }
    }

    private void NavPressed(BaseButton.ButtonEventArgs obj)
    {
        SwitchMode(ShuttleConsoleMode.Nav);
    }

    // WOLFGATE(Shuttles) START: ship mode
    private void ShipPressed(BaseButton.ButtonEventArgs obj)
    {
        SwitchMode(ShuttleConsoleMode.Ship);
    }
    // WOLFGATE END

    // WOLFGATE(ShipAccess) START: access tab
    private void AccessPressed(BaseButton.ButtonEventArgs obj)
    {
        SwitchMode(ShuttleConsoleMode.Access);
    }
    // WOLFGATE END

    private void MapPressed(BaseButton.ButtonEventArgs obj)
    {
        SwitchMode(ShuttleConsoleMode.Map);
    }

    private void DockPressed(BaseButton.ButtonEventArgs obj)
    {
        SwitchMode(ShuttleConsoleMode.Dock);
    }

    private void SetupMode(ShuttleConsoleMode mode)
    {
        switch (mode)
        {
            // WOLFGATE(ShipShields) START: expose allocation controls at the helm.
            case ShuttleConsoleMode.Shields:
                _shieldScreen.Visible = true;
                break;
            // WOLFGATE END
            case ShuttleConsoleMode.Nav:
                NavContainer.Visible = true;
                break;
            // WOLFGATE(Shuttles) START: ship mode
            case ShuttleConsoleMode.Ship:
                WfSetShipMode(true);
                break;
            // WOLFGATE END
            // WOLFGATE(ShipAccess) START: access tab
            case ShuttleConsoleMode.Access:
                WfSetAccessMode(true);
                break;
            // WOLFGATE END
            // WOLFGATE(SectorControl) START: show the sector map in its mode
            case ShuttleConsoleMode.Sector:
                WfSetSectorMode(true);
                break;
            // WOLFGATE END
            case ShuttleConsoleMode.Map:
                MapContainer.Visible = true;
                MapContainer.Startup();
                break;
            case ShuttleConsoleMode.Dock:
                DockContainer.Visible = true;
                break;
            default:
                throw new NotImplementedException();
        }
    }

    public void SwitchMode(ShuttleConsoleMode mode)
    {
        if (_mode == mode)
            return;

        _mode = mode;
        ClearModes(mode);
        SetupMode(_mode);
    }

    public enum ShuttleConsoleMode : byte
    {
        Nav,
        Ship, // WOLFGATE(Shuttles)
        Access, // WOLFGATE(ShipAccess)
        Map,
        Dock,
        Shields, // WOLFGATE(ShipShields): shield allocation mode.
        Sector, // WOLFGATE(SectorControl): the sector map mode.
    }

    public void UpdateState(EntityUid owner, ShuttleBoundUserInterfaceState cState)
    {
        var coordinates = _entManager.GetCoordinates(cState.NavState.Coordinates);
        NavContainer.SetShuttle(coordinates?.EntityId);
        NavContainer.SetConsole(owner);
        MapContainer.SetShuttle(coordinates?.EntityId);
        MapContainer.SetConsole(owner);
        // WOLFGATE(Shuttles) START: ship screen and collision state
        ShipContainer.SetShuttle(coordinates?.EntityId);
        ShipContainer.SetConsole(owner);
        CollisionBanner.SetShuttle(coordinates?.EntityId);
        // WOLFGATE END
        WfUpdateTractorCapture(cState.TractorSources); // WOLFGATE(TractorBeam)
        WfAccessUpdateState(coordinates?.EntityId, owner); // WOLFGATE(ShipAccess)
        WfShieldUpdateState(cState.ShieldShunt, cState.NavState.Angle); // WOLFGATE(ShipShields): share authoritative allocation across helms.
        WfSectorUpdateState(owner); // WOLFGATE(SectorControl): the sector map follows the console's map.

        NavContainer.UpdateState(cState.NavState);
        MapContainer.UpdateState(cState.MapState);
        DockContainer.UpdateState(coordinates?.EntityId, cState.DockState);
    }
}
