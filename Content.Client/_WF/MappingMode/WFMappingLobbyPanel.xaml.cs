using Content.Shared._WF.MappingMode;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.MappingMode;

/// <summary>
/// The mapping lobby: new map, join by code, sessions to rejoin and the player's library.
/// <see cref="WFMappingLobbyUIController"/> wires it up.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFMappingLobbyPanel : PanelContainer
{
    public event Action<int>? RejoinRequested;

    public WFMappingLobbyPanel()
    {
        RobustXamlLoader.Load(this);
        IntroLabel.SetMessage(Loc.GetString("wf-mapping-mode-lobby-intro"));
        GuideButton.OnPressed += _ => WFMappingGuideLauncher.Open();
    }

    /// <summary>Lists the sessions the player is still a member of.</summary>
    public void SetRejoinable(IReadOnlyList<WFMappingRejoinInfo> sessions)
    {
        RejoinList.RemoveAllChildren();
        if (sessions.Count == 0)
        {
            RejoinList.AddChild(new Label
            {
                Text = Loc.GetString("wf-mapping-mode-lobby-sessions-none"),
                StyleClasses = { "LabelSubText" },
            });
            return;
        }

        foreach (var session in sessions)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            row.AddChild(new Label
            {
                Text = Loc.GetString("wf-mapping-mode-lobby-session-entry", ("name", session.Name),
                    ("owner", session.OwnerName), ("count", session.MemberCount)),
                HorizontalExpand = true,
                ClipText = true,
            });

            var id = session.Id;
            var rejoin = new Button { Text = Loc.GetString("wf-mapping-mode-lobby-rejoin") };
            rejoin.OnPressed += _ => RejoinRequested?.Invoke(id);
            row.AddChild(rejoin);
            RejoinList.AddChild(row);
        }
    }

    public void SetLibrary(WFMappingLibraryEvent? library)
    {
        LibraryList.SetLibrary(library);
        LibraryUsage.Text = library == null
            ? string.Empty
            : Loc.GetString("wf-mapping-mode-library-usage",
                ("maps", library.Maps.Count),
                ("maxMaps", library.MaxMaps),
                ("used", WFMappingLibraryList.FormatMiB(library.Bytes)),
                ("max", WFMappingLibraryList.FormatMiB(library.MaxBytes)));
    }

    public void SetResult(WFMappingResult? result)
    {
        WFMappingMenuWindow.ShowResult(ResultLabel, result);
    }
}
