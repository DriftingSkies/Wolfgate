using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WF.MappingMode.Panels;

/// <summary>What this client shows while mapping: walls, subfloor, decals, markers, lighting and links.</summary>
[GenerateTypedNameReferences]
public sealed partial class WFMappingLayersPanel : BoxContainer
{
    private readonly WFMappingClientSystem _mapping = default!;
    private readonly Dictionary<WFMappingLayer, CheckBox> _boxes = new();

    /// <summary>Under the Links box: what the layer has to draw on this level, while it is on.</summary>
    private readonly RichTextLabel? _linksHint;

    /// <summary>Only for the XAML loader; use the constructor that takes what the panel needs.</summary>
    public WFMappingLayersPanel()
    {
        RobustXamlLoader.Load(this);
    }

    public WFMappingLayersPanel(WFMappingClientSystem mapping) : this()
    {
        _mapping = mapping;

        foreach (var layer in WFMappingClientSystem.Layers)
        {
            var box = new CheckBox
            {
                Text = Loc.GetString($"wf-mapping-screen-layer-{layer.ToString().ToLowerInvariant()}"),
                Pressed = mapping.GetLayer(layer),
            };
            box.OnToggled += args => _mapping.SetLayer(layer, args.Pressed);
            _boxes[layer] = box;
            LayerList.AddChild(box);

            if (layer != WFMappingLayer.Links)
                continue;

            _linksHint = new RichTextLabel { HorizontalExpand = true, Margin = new Thickness(24, 0, 0, 2) };
            LayerList.AddChild(_linksHint);
        }

        UpdateLinksHint();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        if (_linksHint == null)
            return;

        _mapping.Links.SnapshotChanged += UpdateLinksHint;
        _mapping.Links.Changed += UpdateLinksHint;
        UpdateLinksHint();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        if (_linksHint == null)
            return;

        _mapping.Links.SnapshotChanged -= UpdateLinksHint;
        _mapping.Links.Changed -= UpdateLinksHint;
    }

    /// <summary>Shows each layer's current state, which keys and other menus can change too.</summary>
    public void Sync()
    {
        foreach (var (layer, box) in _boxes)
        {
            box.Pressed = _mapping.GetLayer(layer);
        }

        UpdateLinksHint();
    }

    /// <summary>Says what the Links layer has to draw on this level, so an empty level doesn't look broken.</summary>
    private void UpdateLinksHint()
    {
        if (_linksHint == null)
            return;

        var links = _mapping.Links;
        _linksHint.Visible = links.ShowAll;
        if (!links.ShowAll)
            return;

        var (signals, lists) = links.CountOnViewedLevel();
        _linksHint.SetMessage(FormattedMessage.FromUnformatted(signals + lists == 0
            ? Loc.GetString("wf-mapping-screen-layer-links-none")
            : Loc.GetString("wf-mapping-screen-layer-links-count", ("links", signals), ("lists", lists))));
    }
}
