using System.Numerics;
using Content.Client._WF.MappingMode.Modes;
using Content.Client._WF.Spawning;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.ContentPack;
using Robust.Shared.Input;
using Robust.Shared.Utility;

namespace Content.Client._WF.MappingMode.Palette;

/// <summary>
/// The mapping screen's palette: Entities (the Wolfgate spawn menu), Tiles and Decals tabs, and a strip of the last
/// entries picked. Choosing an entry starts placing it through <see cref="WFMappingBuildModeSystem"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFMappingPalette : BoxContainer
{
    [Dependency] private ILogManager _log = default!;
    [Dependency] private IResourceManager _resources = default!;

    private static readonly ResPath StorePath = new("/Mapping/palette.yml");

    private readonly WFMappingBuildModeSystem _modes = default!;
    private readonly WFMappingPaletteIcons _icons = new();
    private readonly WFMappingPaletteStore _store = default!;
    private readonly WolfgateSpawnPanel _entities = default!;
    private readonly WFMappingTilePalette _tiles = default!;
    private readonly WFMappingDecalPalette _decals = default!;

    /// <summary>Only for the XAML loader; use the constructor that takes what the panel needs.</summary>
    public WFMappingPalette()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public WFMappingPalette(WFMappingBuildModeSystem modes) : this()
    {
        _modes = modes;
        _store = Load();

        _entities = new WolfgateSpawnPanel { PlacementControlsVisible = false };
        _tiles = new WFMappingTilePalette(_store, _icons);
        _decals = new WFMappingDecalPalette(_store, _icons);
        _decals.SetSettings(modes.DecalSettings);

        Tabs.AddChild(_entities);
        Tabs.AddChild(_tiles);
        Tabs.AddChild(_decals);
        TabContainer.SetTabTitle(_entities, Loc.GetString("wf-mapping-screen-tab-entities"));
        TabContainer.SetTabTitle(_tiles, Loc.GetString("wf-mapping-screen-tab-tiles"));
        TabContainer.SetTabTitle(_decals, Loc.GetString("wf-mapping-screen-tab-decals"));
        Tabs.OnTabChanged += tab =>
        {
            if (tab == 0)
                _entities.OnShown();
        };

        _entities.OnEntrySelected += entry =>
        {
            if (entry == null)
                _modes.ClearEntry();
            else
                _modes.BeginPlacing(new WFMappingPaletteEntry(WFMappingPaletteKind.Entity, entry.Id));
        };
        _entities.EntryNote = entry => _modes.UnsavedNote(entry.Id);
        _entities.OnEntryContext += entry =>
        {
            var chosen = new WFMappingPaletteEntry(WFMappingPaletteKind.Entity, entry.Id);
            var items = new List<(string Text, Action Action)>
            {
                (Loc.GetString("wf-mapping-screen-add-quick-select"), () => _modes.RequestQuickSelect(chosen)),
            };

            if (_modes.TryGetSpawner(chosen, out _))
                items.Add((Loc.GetString("wf-mapping-screen-use-spawner"), () => _modes.UseSpawner(chosen)));

            WFMappingEntryMenu.Open(items.ToArray());
        };

        _tiles.EntrySelected += _modes.BeginPlacing;
        _tiles.QuickSelectRequested += _modes.RequestQuickSelect;
        _tiles.StoreChanged += Save;

        _decals.EntrySelected += _modes.BeginPlacing;
        _decals.QuickSelectRequested += _modes.RequestQuickSelect;
        _decals.StoreChanged += Save;
        _decals.SettingsChanged += _modes.SetDecalSettings;

        _modes.EntryChanged += OnEntryChanged;
        _modes.PrototypePicked += OnPicked;
        _modes.SpawnersChanged += _entities.RefreshEntries;

        RebuildStrip();
        OnEntryChanged(_modes.Entry);
    }

    /// <summary>Drops the subscriptions to the build mode system, before the palette is thrown away.</summary>
    public void Unbind()
    {
        _modes.EntryChanged -= OnEntryChanged;
        _modes.PrototypePicked -= OnPicked;
        _modes.SpawnersChanged -= _entities.RefreshEntries;
    }

    private void OnEntryChanged(WFMappingPaletteEntry? entry)
    {
        _entities.SetSelected(entry is { Kind: WFMappingPaletteKind.Entity } e ? e.Id : null);
        _tiles.SetSelected(entry is { Kind: WFMappingPaletteKind.Tile } t ? t.Id : null);
        if (entry is not { Kind: WFMappingPaletteKind.Decal })
            _decals.SetSelected(null, null);

        if (entry is not { } chosen)
            return;

        _store.AddRecent(chosen);
        Save();
        RebuildStrip();
    }

    private void OnPicked(WFMappingPaletteEntry entry)
    {
        if (entry.Kind != WFMappingPaletteKind.Decal)
            return;

        _decals.SetSettings(_modes.DecalSettings);
        _decals.SetSelected(entry.Id, entry.Color);
    }

    private void RebuildStrip()
    {
        StripBox.RemoveAllChildren();
        foreach (var entry in _store.Strip)
        {
            var button = new Button
            {
                ToolTip = _icons.Name(entry),
                MinSize = new Vector2(36, 36),
            };
            button.AddChild(new TextureRect
            {
                Texture = _icons.Get(entry),
                Modulate = entry.Kind == WFMappingPaletteKind.Decal ? entry.Color ?? Color.White : Color.White,
                SetSize = new Vector2(28, 28),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
            });
            button.OnPressed += _ => _modes.BeginPlacing(entry);
            button.OnKeyBindDown += args =>
            {
                if (args.Function != EngineKeyFunctions.UIRightClick)
                    return;

                args.Handle();
                WFMappingEntryMenu.Open((Loc.GetString("wf-mapping-screen-add-quick-select"),
                    () => _modes.RequestQuickSelect(entry)));
            };
            StripBox.AddChild(button);
        }
    }

    private WFMappingPaletteStore Load()
    {
        try
        {
            if (_resources.UserData.Exists(StorePath.Directory) &&
                _resources.UserData.Exists(StorePath) &&
                _resources.UserData.TryReadAllText(StorePath, out var text))
                return WFMappingPaletteStore.Read(text);
        }
        catch (Exception e)
        {
            _log.GetSawmill("wf.mapping").Warning($"Reading {StorePath} failed: {e.Message}");
        }

        return new WFMappingPaletteStore();
    }

    private void Save()
    {
        try
        {
            var dir = StorePath.Directory;
            if (!_resources.UserData.Exists(dir))
                _resources.UserData.CreateDir(dir);

            _resources.UserData.WriteAllText(StorePath, _store.Write());
        }
        catch (Exception e)
        {
            _log.GetSawmill("wf.mapping").Warning($"Writing {StorePath} failed: {e.Message}");
        }
    }
}
