using System.Linq;
using System.Numerics;
using Content.Client._WF.MappingMode.Modes;
using Content.Shared.Decals;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Prototypes;

namespace Content.Client._WF.MappingMode.Palette;

/// <summary>
/// The palette's Decals tab: search, tag categories with Favourites and Recent, and the colour (sliders or a colour
/// palette), rotation, snap, z-index and cleanable settings of the decal placer.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFMappingDecalPalette : BoxContainer
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    private const int CategoryAll = 0;
    private const int CategoryFavourites = 1;
    private const int CategoryRecent = 2;

    private readonly WFMappingPaletteStore _store = default!;
    private readonly WFMappingPaletteIcons _icons = default!;
    private readonly FloatSpinBox _rotation = default!;
    private readonly List<string> _tags = new();
    private readonly List<ColorPalettePrototype> _palettes = new();

    private int _category = CategoryAll;
    private string? _selected;
    private Color _color = Color.White;
    private bool _updating;

    /// <summary>Raised when a decal is clicked, or the colour of the selected one changes.</summary>
    public event Action<WFMappingPaletteEntry>? EntrySelected;

    /// <summary>Raised from a decal's right-click menu.</summary>
    public event Action<WFMappingPaletteEntry>? QuickSelectRequested;

    /// <summary>Raised after a favourite is toggled, so the store can be saved.</summary>
    public event Action? StoreChanged;

    /// <summary>Raised when rotation, snap, z-index or cleanable change.</summary>
    public event Action<WFMappingDecalSettings>? SettingsChanged;

    /// <summary>Only for the XAML loader; use the constructor that takes what the panel needs.</summary>
    public WFMappingDecalPalette()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public WFMappingDecalPalette(WFMappingPaletteStore store, WFMappingPaletteIcons icons) : this()
    {
        _store = store;
        _icons = icons;

        _rotation = new FloatSpinBox(90f, 0) { HorizontalExpand = true };
        RotationRow.AddChild(_rotation);

        CategoryMenu.AddItem(Loc.GetString("wf-mapping-screen-filter-all"), CategoryAll);
        CategoryMenu.AddItem(Loc.GetString("wf-mapping-screen-filter-favourites"), CategoryFavourites);
        CategoryMenu.AddItem(Loc.GetString("wf-mapping-screen-filter-recent"), CategoryRecent);
        foreach (var tag in _prototypes.EnumeratePrototypes<DecalPrototype>()
                     .Where(d => d.ShowMenu)
                     .SelectMany(d => d.Tags)
                     .Distinct()
                     .OrderBy(t => t, StringComparer.Ordinal))
        {
            CategoryMenu.AddItem(tag, CategoryRecent + 1 + _tags.Count);
            _tags.Add(tag);
        }

        CategoryMenu.OnItemSelected += args =>
        {
            CategoryMenu.SelectId(args.Id);
            _category = args.Id;
            Refresh();
        };

        foreach (var palette in _prototypes.EnumeratePrototypes<ColorPalettePrototype>()
                     .Where(p => !p.Hidden)
                     .OrderBy(p => p.Name, StringComparer.Ordinal))
        {
            PaletteMenu.AddItem(palette.Name, _palettes.Count);
            _palettes.Add(palette);
        }

        PaletteMenu.Disabled = _palettes.Count == 0;
        PaletteMenu.OnItemSelected += args =>
        {
            PaletteMenu.SelectId(args.Id);
            BuildSwatches();
        };
        BuildSwatches();

        SearchBar.OnTextChanged += _ => Refresh();
        ColorPicker.OnColorChanged += color =>
        {
            _color = color;
            ColorUpdated();
        };
        UseColorBox.OnToggled += _ => ColorUpdated();
        SnapBox.OnToggled += _ => RaiseSettings();
        CleanableBox.OnToggled += _ => RaiseSettings();
        ZIndexBox.ValueChanged += _ => RaiseSettings();
        _rotation.OnValueChanged += _ => RaiseSettings();

        Refresh();
    }

    /// <summary>The colour decals are laid with, or null for their own.</summary>
    public Color? CurrentColor => UseColorBox.Pressed ? _color : null;

    public WFMappingDecalSettings Settings =>
        new(_rotation.Value, SnapBox.Pressed, ZIndexBox.Value, CleanableBox.Pressed);

    /// <summary>Shows settings set elsewhere, such as an eyedropped decal's rotation, without raising events.</summary>
    public void SetSettings(WFMappingDecalSettings settings)
    {
        _updating = true;
        try
        {
            _rotation.Value = settings.Rotation;
            SnapBox.Pressed = settings.Snap;
            ZIndexBox.OverrideValue(settings.ZIndex);
            CleanableBox.Pressed = settings.Cleanable;
        }
        finally
        {
            _updating = false;
        }
    }

    /// <summary>Highlights a decal, and takes its colour, without raising <see cref="EntrySelected"/>.</summary>
    public void SetSelected(string? id, Color? color)
    {
        _selected = id;
        if (color is { } picked)
        {
            _color = picked;
            ColorPicker.Color = picked;
            UseColorBox.Pressed = true;
        }

        Refresh();
    }

    /// <summary>Shows the colours of the chosen colour palette as swatches.</summary>
    private void BuildSwatches()
    {
        PaletteGrid.RemoveAllChildren();
        var index = PaletteMenu.SelectedId;
        if (index < 0 || index >= _palettes.Count)
            return;

        foreach (var (name, color) in _palettes[index].Colors)
        {
            var swatch = new ContainerButton
            {
                MinSize = new Vector2(16, 16),
                ToolTip = Loc.GetString("wf-mapping-screen-decal-swatch", ("name", name), ("hex", color.ToHex())),
                TooltipDelay = 0,
            };
            swatch.AddChild(new PanelContainer
            {
                PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = color,
                    BorderColor = Color.Black,
                    BorderThickness = new Thickness(1),
                },
            });
            swatch.OnPressed += _ => PickColor(color);
            PaletteGrid.AddChild(swatch);
        }
    }

    /// <summary>Takes a palette colour as the decal colour and turns Use colour on, as picking one means to use it.</summary>
    private void PickColor(Color color)
    {
        _color = color;
        ColorPicker.Color = color;
        UseColorBox.Pressed = true;
        ColorUpdated();
    }

    private void ColorUpdated()
    {
        Refresh();
        if (_selected != null)
            EntrySelected?.Invoke(new WFMappingPaletteEntry(WFMappingPaletteKind.Decal, _selected, CurrentColor));
    }

    private void RaiseSettings()
    {
        if (!_updating)
            SettingsChanged?.Invoke(Settings);
    }

    /// <summary>Rebuilds the grid for the search and category.</summary>
    public void Refresh()
    {
        DecalGrid.RemoveAllChildren();

        var search = SearchBar.Text.Trim();
        IEnumerable<DecalPrototype> decals;
        switch (_category)
        {
            case CategoryFavourites:
                decals = _prototypes.EnumeratePrototypes<DecalPrototype>()
                    .Where(d => _store.IsFavourite(WFMappingPaletteKind.Decal, d.ID))
                    .OrderBy(d => d.ID, StringComparer.Ordinal);
                break;
            case CategoryRecent:
                decals = _store.Recent(WFMappingPaletteKind.Decal)
                    .Select(id => _prototypes.TryIndex<DecalPrototype>(id, out var decal) ? decal : null)
                    .Where(d => d != null)
                    .Select(d => d!);
                break;
            default:
                var tag = _category > CategoryRecent && _category - CategoryRecent - 1 < _tags.Count
                    ? _tags[_category - CategoryRecent - 1]
                    : null;
                decals = _prototypes.EnumeratePrototypes<DecalPrototype>()
                    .Where(d => d.ShowMenu && (tag == null || d.Tags.Contains(tag)))
                    .OrderBy(d => d.ID, StringComparer.Ordinal);
                break;
        }

        if (search.Length > 0)
            decals = decals.Where(d => d.ID.Contains(search, StringComparison.OrdinalIgnoreCase));

        var count = 0;
        var modulate = CurrentColor ?? Color.White;
        foreach (var decal in decals)
        {
            DecalGrid.AddChild(Button(decal, modulate));
            count++;
        }

        EmptyLabel.Visible = count == 0;
    }

    private Control Button(DecalPrototype decal, Color modulate)
    {
        var id = decal.ID;
        var name = _store.IsFavourite(WFMappingPaletteKind.Decal, id)
            ? Loc.GetString("wf-mapping-screen-favourite-name", ("name", id))
            : id;
        var button = new TextureButton
        {
            TextureNormal = _icons.Decal(id),
            ToolTip = name,
            Modulate = modulate,
            MinSize = new Vector2(36, 36),
        };
        button.OnPressed += _ => Select(id);
        button.OnKeyBindDown += args =>
        {
            if (args.Function != EngineKeyFunctions.UIRightClick)
                return;

            args.Handle();
            OpenMenu(id);
        };

        if (id != _selected)
            return button;

        var highlight = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#3d5a80") },
        };
        highlight.AddChild(button);
        return highlight;
    }

    private void Select(string id)
    {
        if (!_prototypes.TryIndex<DecalPrototype>(id, out var decal))
            return;

        _selected = id;
        if (AutoBox.Pressed)
        {
            _updating = true;
            try
            {
                CleanableBox.Pressed = decal.DefaultCleanable;
                UseColorBox.Pressed = decal.DefaultCustomColor;
                SnapBox.Pressed = decal.DefaultSnap;
            }
            finally
            {
                _updating = false;
            }

            SettingsChanged?.Invoke(Settings);
        }

        Refresh();
        EntrySelected?.Invoke(new WFMappingPaletteEntry(WFMappingPaletteKind.Decal, id, CurrentColor));
    }

    private void OpenMenu(string id)
    {
        var entry = new WFMappingPaletteEntry(WFMappingPaletteKind.Decal, id, CurrentColor);
        var favourite = _store.IsFavourite(WFMappingPaletteKind.Decal, id);
        WFMappingEntryMenu.Open(
            (Loc.GetString("wf-mapping-screen-add-quick-select"), () => QuickSelectRequested?.Invoke(entry)),
            (Loc.GetString(favourite ? "wf-mapping-screen-unfavourite" : "wf-mapping-screen-favourite"), () =>
            {
                _store.ToggleFavourite(WFMappingPaletteKind.Decal, id);
                StoreChanged?.Invoke();
                Refresh();
            }));
    }
}
