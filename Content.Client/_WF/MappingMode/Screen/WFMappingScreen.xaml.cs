using System.Numerics;
using Content.Client.UserInterface.Screens;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Content.Client.UserInterface.Systems.Chat.Widgets;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._WF.MappingMode.Screen;

/// <summary>
/// The screen mappers get in a session: the palette on the left, the viewport with the mode bar, quick-select bar
/// and cursor readout in the middle, and the properties tabs over the chat on the right. Built once at startup for
/// every client, so it only lays out its hosts and places the mode bar; <see cref="WFMappingScreenUIController"/>
/// fills them, collapses a dock column whose panels are all undocked and keeps the bar's layout.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFMappingScreen : InGameScreen
{
    private const float DockSplitWidth = 2f;

    /// <summary>The chat's starting height in the right column.</summary>
    private const float ChatHeight = 260f;

    /// <summary>Space left between the mode bar in its default spot and what it sits above or below.</summary>
    private const float BarGap = 8f;

    private WFMappingScreenLayout _layout = new();
    private Vector2? _barPosition;

    /// <summary>The mode bar's sizes lying flat and standing upright, as last measured.</summary>
    private (int Buttons, float Scale, Vector2 Flat, Vector2 Upright)? _barSizes;

    /// <summary>Raised when a drag of the mode bar ends, with the layout to save.</summary>
    public event Action<WFMappingScreenLayout>? LayoutChanged;

    /// <summary>Where the mode bar is kept; a new layout puts it in its default spot.</summary>
    public WFMappingScreenLayout Layout => _layout;

    /// <summary>The split each dock had been dragged to before it collapsed, or null when it was never dragged.</summary>
    private float? _leftSplit;

    private float? _rightSplit;

    /// <summary>Whether the palette column is hidden.</summary>
    public bool LeftCollapsed => !LeftDock.Visible;

    /// <summary>Whether the tabs and chat column is hidden; the chat then floats over the viewport.</summary>
    public bool RightCollapsed => !RightDock.Visible;

    public WFMappingScreen()
    {
        RobustXamlLoader.Load(this);

        SetAnchorPreset(ScreenSplit, LayoutPreset.Wide);
        SetAnchorPreset(MainViewport, LayoutPreset.Wide);
        SetAnchorAndMarginPreset(TopBar, LayoutPreset.TopLeft, margin: 10);

        SetAnchorPreset(QuickBarHost, LayoutPreset.CenterBottom);
        SetMarginBottom(QuickBarHost, -10);
        SetMarginTop(QuickBarHost, -10);
        SetGrowHorizontal(QuickBarHost, GrowDirection.Both);
        SetGrowVertical(QuickBarHost, GrowDirection.Begin);

        SetAnchorPreset(StatusHost, LayoutPreset.BottomLeft);
        SetMarginLeft(StatusHost, 10);
        SetMarginBottom(StatusHost, -10);
        SetMarginTop(StatusHost, -10);
        SetGrowVertical(StatusHost, GrowDirection.Begin);

        SetAnchorPreset(ModeBar, LayoutPreset.TopLeft);
        ModeBar.Dragged += OnBarDragged;
        ModeBar.DragEnded += DropBar;
    }

    /// <summary>Uses a saved or a fresh layout for the mode bar.</summary>
    public void SetLayout(WFMappingScreenLayout layout)
    {
        _layout = layout;
        PlaceModeBar();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        PlaceChatSplit();
        if (!ModeBar.Dragging)
            PlaceModeBar();
    }

    /// <summary>
    /// Starts the right column with the chat about <see cref="ChatHeight"/> tall at the bottom; the chat fills its part of
    /// the split, so the tabs and the chat share the whole column with no gap. A dragged split is left alone.
    /// </summary>
    private void PlaceChatSplit()
    {
        if (RightColumn.State != SplitContainer.SplitState.Auto || Chat.Parent != RightColumn || RightColumn.Size.Y <= 0)
            return;

        RightColumn.SplitCenter = MathF.Max(RightColumn.Size.Y / 2f, RightColumn.Size.Y - ChatHeight);
    }

    /// <summary>Puts the mode bar where the layout says, or in its default spot.</summary>
    public void PlaceModeBar()
    {
        var area = ViewportContainer.Size;
        if (area.X <= 0f || area.Y <= 0f || ModeBar.Buttons.ChildCount == 0)
            return;

        Vector2 position;
        bool vertical;
        if (_layout.Bar is { } fraction)
        {
            vertical = Fit(_layout.Vertical, area);
            position = WFMappingScreenLayout.Place(fraction, area, BarSize(vertical));
        }
        else
        {
            (position, vertical) = DefaultBarPlace(area);
        }

        ModeBar.Vertical = vertical;
        SetBarPosition(position);
    }

    /// <summary>
    /// The default spot: on the left, flat if it fits the viewport's width, just above whatever of the quick bar and
    /// the cursor readout lies under it, and below the menu bar and a floating chat.
    /// </summary>
    public (Vector2 Position, bool Vertical) DefaultBarPlace(Vector2 area)
    {
        var margin = WFMappingScreenLayout.Margin;
        var vertical = BarSize(false).X > area.X - margin * 2f;
        var size = BarSize(vertical);
        var left = margin;
        var right = margin + size.X;

        var bottom = area.Y - margin;
        foreach (var below in new Control[] { QuickBarHost, StatusHost })
        {
            if (Overlaps(below, left, right))
                bottom = Math.Min(bottom, below.Position.Y - BarGap);
        }

        var top = margin;
        foreach (var above in new Control[] { TopBar, Chat })
        {
            if (above.Parent == ViewportContainer && Overlaps(above, left, right))
                top = Math.Max(top, above.Position.Y + above.Size.Y + BarGap);
        }

        return (new Vector2(left, Math.Max(top, bottom - size.Y)), vertical);
    }

    /// <summary>Whether a shown control in the viewport spans any of the columns from left to right.</summary>
    private static bool Overlaps(Control control, float left, float right)
    {
        return control.Visible && control.Size.X > 0f && control.Size.Y > 0f &&
               control.Position.X < right && control.Position.X + control.Size.X > left;
    }

    /// <summary>The orientation asked for, unless the bar wouldn't fit the viewport that way.</summary>
    private bool Fit(bool vertical, Vector2 area)
    {
        var room = area - new Vector2(WFMappingScreenLayout.Margin * 2f);
        if (!vertical && BarSize(false).X > room.X)
            return true;

        if (vertical && BarSize(true).Y > room.Y)
            return false;

        return vertical;
    }

    /// <summary>
    /// The mode bar's size lying flat or standing upright, measured again when its buttons, the UI scale or its
    /// measured size in its current orientation change.
    /// </summary>
    private Vector2 BarSize(bool vertical)
    {
        var buttons = ModeBar.Buttons.ChildCount;
        if (_barSizes is not { } sizes || sizes.Buttons != buttons || !MathHelper.CloseTo(sizes.Scale, UIScale) ||
            ModeBar.IsMeasureValid &&
            (ModeBar.DesiredSize - (ModeBar.Vertical ? sizes.Upright : sizes.Flat)).LengthSquared() > 0.25f)
        {
            sizes = (buttons, UIScale, ModeBar.SizeFor(false), ModeBar.SizeFor(true));
            _barSizes = sizes;
        }

        return vertical ? sizes.Upright : sizes.Flat;
    }

    private void SetBarPosition(Vector2 position)
    {
        if (_barPosition == position)
            return;

        _barPosition = position;
        LayoutContainer.SetPosition(ModeBar, position);
    }

    private void OnBarDragged(Vector2 globalTopLeft)
    {
        MoveBar(globalTopLeft - ViewportContainer.GlobalPosition);
    }

    /// <summary>Moves the mode bar's top-left to a spot in the viewport, kept inside it, as a drag does.</summary>
    public void MoveBar(Vector2 topLeft)
    {
        var area = ViewportContainer.Size;
        SetBarPosition(Vector2.Clamp(topLeft, Vector2.Zero, Vector2.Max(area - ModeBar.Size, Vector2.Zero)));
    }

    /// <summary>Keeps where the bar was dropped, snapped to a near edge, turns it to suit that edge and saves it.</summary>
    public void DropBar()
    {
        if (_barPosition is not { } position)
            return;

        var fraction = WFMappingScreenLayout.Fraction(position, ViewportContainer.Size, ModeBar.Size);
        _layout.Bar = fraction;
        _layout.Vertical = WFMappingScreenLayout.VerticalAfterDrop(fraction, ModeBar.Vertical);
        PlaceModeBar();
        LayoutChanged?.Invoke(_layout);
    }

    public override ChatBox ChatBox => Chat;

    /// <summary>Hides the palette column so the viewport takes its width, or brings it back.</summary>
    public void SetLeftCollapsed(bool collapsed)
    {
        Collapse(ScreenSplit, LeftDock, collapsed, ref _leftSplit);
    }

    /// <summary>
    /// Hides the tabs column so the viewport takes its width, or brings it back. The chat leaves with the column and
    /// floats at the viewport's top right meanwhile.
    /// </summary>
    public void SetRightCollapsed(bool collapsed)
    {
        Collapse(RightSplit, RightDock, collapsed, ref _rightSplit);
        if (collapsed == (Chat.Parent == ViewportContainer))
            return;

        Chat.Orphan();
        if (!collapsed)
        {
            RightColumn.AddChild(Chat);
            return;
        }

        ViewportContainer.AddChild(Chat);
        SetAnchorPreset(Chat, LayoutPreset.TopRight);
        SetMarginLeft(Chat, -430);
        SetMarginRight(Chat, -10);
        SetMarginTop(Chat, 50);
        SetMarginBottom(Chat, 290);
    }

    private static void Collapse(SplitContainer split, Control dock, bool collapsed, ref float? manualSplit)
    {
        if (dock.Visible != collapsed)
            return;

        if (collapsed)
        {
            manualSplit = split.State == SplitContainer.SplitState.Manual ? split.SplitCenter : null;
            dock.Visible = false;
            split.ResizeMode = SplitContainer.SplitResizeMode.NotResizable;
            split.SplitWidth = 0f;
            split.State = SplitContainer.SplitState.Auto;
            return;
        }

        dock.Visible = true;
        split.ResizeMode = SplitContainer.SplitResizeMode.RespectChildrenMinSize;
        split.SplitWidth = DockSplitWidth;
        if (manualSplit is { } center)
            split.SplitCenter = center;

        manualSplit = null;
    }

    /// <summary>The chat sits in the right dock and is sized by its split, so stored chat sizes don't apply.</summary>
    public override void SetChatSize(Vector2 size)
    {
    }
}
