using System.Numerics;
using Content.Shared._WF.MappingMode;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WF.MappingMode.Template;

/// <summary>
/// The Template tab: load or clear the PNG, share it with the session or unshare it, show, lock and layer it, and type
/// or slide its position, scale, pixels per tile, rotation and opacity. Follows the template system's changes, so
/// drags in Template mode and other members' moves show here.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFMappingTemplatePanel : BoxContainer
{
    private readonly WFMappingTemplateSystem _template = default!;
    private readonly FloatSpinBox _x = new(0.5f, 2);
    private readonly FloatSpinBox _y = new(0.5f, 2);
    private readonly FloatSpinBox _scaleX = new(0.05f, 2);
    private readonly FloatSpinBox _scaleY = new(0.05f, 2);
    private readonly FloatSpinBox _rotation = new(1f, 1);
    private readonly SpinBox _pixels = new();
    private bool _updating;

    /// <summary>Only for the XAML loader; use the constructor that takes the template system.</summary>
    public WFMappingTemplatePanel()
    {
        RobustXamlLoader.Load(this);
    }

    public WFMappingTemplatePanel(WFMappingTemplateSystem template) : this()
    {
        _template = template;

        AddField(PositionRow, "wf-mapping-template-x", _x);
        AddField(PositionRow, "wf-mapping-template-y", _y);
        AddField(ScaleRow, "wf-mapping-template-scale-x", _scaleX);
        AddField(ScaleRow, "wf-mapping-template-scale-y", _scaleY);
        AddField(RotationRow, "wf-mapping-template-degrees", _rotation);

        _pixels.InitDefaultButtons();
        _pixels.MinWidth = 110;
        _pixels.IsValid = value => value is >= WFMappingTemplateSettings.MinPixelsPerTile
            and <= WFMappingTemplateSettings.MaxPixelsPerTile;
        PixelsRow.AddChild(_pixels);

        LayerMenu.AddItem(Loc.GetString("wf-mapping-template-layer-under"), (int) WFMappingTemplateLayer.Under);
        LayerMenu.AddItem(Loc.GetString("wf-mapping-template-layer-over"), (int) WFMappingTemplateLayer.Over);

        HintLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("wf-mapping-template-hint")));

        LoadButton.OnPressed += _ => _template.Load();
        ClearButton.OnPressed += _ => _template.Clear();
        ShareButton.OnPressed += _ => _template.Share();
        UnshareButton.OnPressed += _ => _template.Unshare();
        ResetButton.OnPressed += _ => _template.Reset();
        VisibleCheck.OnToggled += args => Edit(s => s.Visible = args.Pressed);
        LockCheck.OnToggled += args => Edit(s => s.Locked = args.Pressed);
        UniformCheck.OnToggled += args => Edit(s => s.Uniform = args.Pressed);
        LayerMenu.OnItemSelected += args =>
        {
            LayerMenu.SelectId(args.Id);
            Edit(s => s.Layer = (WFMappingTemplateLayer) args.Id);
        };

        _x.OnValueChanged += args => Edit(s => s.Position = new Vector2(args.Value, s.Position.Y));
        _y.OnValueChanged += args => Edit(s => s.Position = new Vector2(s.Position.X, args.Value));
        _scaleX.OnValueChanged += args => Edit(s => s.SetScaleX(args.Value));
        _scaleY.OnValueChanged += args => Edit(s => s.SetScaleY(args.Value));
        _rotation.OnValueChanged += args => Edit(s => s.Rotation = args.Value);
        _pixels.ValueChanged += args => Edit(s => s.PixelsPerTile = args.Value);
        RotationSlider.OnValueChanged += range => Edit(s => s.Rotation = range.Value);
        OpacitySlider.OnValueChanged += range => Edit(s => s.Opacity = range.Value);

        _template.Changed += Refresh;
        Refresh();
    }

    /// <summary>Stops following the template system; called when the screen unloads.</summary>
    public void Unbind()
    {
        _template.Changed -= Refresh;
    }

    private static void AddField(BoxContainer row, string locKey, Control field)
    {
        row.AddChild(new Label { Text = Loc.GetString(locKey), VerticalAlignment = VAlignment.Center });
        field.HorizontalExpand = true;
        row.AddChild(field);
    }

    private void Edit(Action<WFMappingTemplateSettings> change)
    {
        if (_updating || !_template.HasTemplate)
            return;

        change(_template.Settings);
        _template.Modified();
    }

    private void Refresh()
    {
        _updating = true;
        try
        {
            var settings = _template.Settings;
            var texture = _template.Texture;

            LoadButton.Disabled = !_template.CanLoad;
            ClearButton.Disabled = !_template.HasLocal;
            SettingsBox.Visible = texture != null;
            RefreshShare();

            if (texture == null)
            {
                InfoLabel.Text = Loc.GetString(_template.CanLoad
                    ? "wf-mapping-template-info-none"
                    : "wf-mapping-template-info-no-session");
                return;
            }

            var size = settings.Size(texture.Size);
            InfoLabel.Text = Loc.GetString("wf-mapping-template-info",
                ("width", texture.Width),
                ("height", texture.Height),
                ("tilesX", MathF.Round(size.X, 1)),
                ("tilesY", MathF.Round(size.Y, 1)));

            VisibleCheck.Pressed = settings.Visible;
            LockCheck.Pressed = settings.Locked;
            UniformCheck.Pressed = settings.Uniform;
            LayerMenu.SelectId((int) settings.Layer);

            SetField(_x, settings.Position.X);
            SetField(_y, settings.Position.Y);
            SetField(_scaleX, settings.ScaleX);
            SetField(_scaleY, settings.ScaleY);
            SetField(_rotation, settings.Rotation);
            if (!_pixels.LineEditControl.HasKeyboardFocus())
                _pixels.OverrideValue(settings.PixelsPerTile);

            if (!RotationSlider.Grabbed)
                RotationSlider.SetValueWithoutEvent(settings.Rotation);

            if (!OpacitySlider.Grabbed)
                OpacitySlider.SetValueWithoutEvent(settings.Opacity);

            OpacityLabel.Text = Loc.GetString("wf-mapping-template-opacity-value",
                ("percent", (int) MathF.Round(settings.Opacity * 100f)));
        }
        finally
        {
            _updating = false;
        }
    }

    /// <summary>The share buttons, who shared the template and how far a transfer is.</summary>
    private void RefreshShare()
    {
        var shared = _template.SharedInfo;
        ShareButton.Disabled = !_template.CanShare;
        UnshareButton.Disabled = shared == null;
        OwnHiddenLabel.Visible = _template.SharedActive && _template.HasLocal;

        var progress = _template.SendProgress ?? _template.ReceiveProgress;
        TransferBar.Visible = progress != null;
        if (progress is { } value)
            TransferBar.Value = value;

        if (_template.SendProgress is { } sent)
        {
            SharedLabel.Text = Loc.GetString("wf-mapping-template-sending", ("percent", Percent(sent)));
        }
        else if (shared == null)
        {
            SharedLabel.Text = Loc.GetString(_template.HasLocal
                ? "wf-mapping-template-not-shared"
                : "wf-mapping-template-share-none");
        }
        else if (_template.SharedActive)
        {
            SharedLabel.Text = Loc.GetString("wf-mapping-template-shared-by", ("name", shared.SharedByName));
        }
        else
        {
            SharedLabel.Text = Loc.GetString("wf-mapping-template-receiving", ("name", shared.SharedByName),
                ("percent", Percent(_template.ReceiveProgress ?? 0f)));
        }
    }

    private static int Percent(float fraction)
    {
        return (int) MathF.Round(fraction * 100f);
    }

    /// <summary>Shows a value unless the player is typing in that field.</summary>
    private static void SetField(FloatSpinBox field, float value)
    {
        if (!field.HasKeyboardFocus())
            field.Value = value;
    }
}
