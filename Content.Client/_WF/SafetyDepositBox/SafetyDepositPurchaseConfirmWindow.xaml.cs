using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.SafetyDepositBox;

/// <summary>Asks before a deposit box is bought, since the cost comes straight out of the bank.</summary>
[GenerateTypedNameReferences]
public sealed partial class SafetyDepositPurchaseConfirmWindow : FancyWindow
{
    /// <summary>The purchase waiting for an answer. Cleared on every close, so Cancel never runs it.</summary>
    private Action? _onConfirmed;

    public SafetyDepositPurchaseConfirmWindow()
    {
        RobustXamlLoader.Load(this);

        ConfirmButton.OnPressed += _ =>
        {
            var confirmed = _onConfirmed;
            Close();
            confirmed?.Invoke();
        };
        CancelButton.OnPressed += _ => Close();
        OnClose += () => _onConfirmed = null;
    }

    /// <summary>Opens the window for one purchase; <paramref name="onConfirmed"/> runs on Buy and replaces any earlier one.</summary>
    public void Ask(string boxName, int cost, Action onConfirmed)
    {
        _onConfirmed = onConfirmed;
        MessageLabel.SetMessage(Loc.GetString("safety-deposit-console-confirm-text",
            ("box", boxName), ("cost", cost.ToString("N0"))));
        OpenCentered();
    }
}
