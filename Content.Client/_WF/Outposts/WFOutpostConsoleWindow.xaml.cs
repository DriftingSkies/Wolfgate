namespace Content.Client._WF.Outposts;

/// <summary>
/// The outpost console: an Overview tab with a map of the outpost and its claim, its name, owner, caps and status, a
/// Saves tab with its save slots, a Trade tab to order supplies down onto the trade hub, a Sell tab, and the ship access
/// tab for who may open its doors.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFOutpostConsoleWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IPlayerManager _player = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    /// <summary>The owner asked for a new name.</summary>
    public event Action<string>? OnRename;

    /// <summary>The owner saves into a slot.</summary>
    public event Action<int>? OnSave;

    /// <summary>The owner loads a slot.</summary>
    public event Action<int>? OnLoad;

    /// <summary>The owner brings a preset down in this outpost's place.</summary>
    public event Action<string>? OnLoadPreset;

    /// <summary>The owner empties a slot.</summary>
    public event Action<int>? OnDelete;

    /// <summary>The owner calls off a load on its way down.</summary>
    public event Action? OnCancelLoad;

    /// <summary>The owner orders one of a Trade listing.</summary>
    public event Action<string>? OnOrder;

    /// <summary>The owner sells the outpost to the game.</summary>
    public event Action? OnSell;

    /// <summary>The owner sets whether the outpost sells when the round ends.</summary>
    public event Action<bool>? OnSellAtRoundEnd;

    /// <summary>The owner offers the outpost to a player at the console, for a price.</summary>
    public event Action<NetUserId, int>? OnOffer;

    /// <summary>The owner takes back their offer.</summary>
    public event Action? OnWithdrawOffer;

    /// <summary>The owner looks again at who stands at the console.</summary>
    public event Action? OnRefreshBuyers;

    private static readonly Color GoodColor = Color.FromHex("#6FCF6F");
    private static readonly Color WarnColor = Color.FromHex("#E8A33D");
    private static readonly Color BadColor = Color.FromHex("#E05A4F");

    private readonly List<(CargoProductPrototype Product, Button Order, Control Row)> _listings = new();
    private readonly List<Label> _orderLabels = new();
    private WFOutpostPendingLoad? _pending;
    private WFOutpostRaidView? _raid;
    private WFOutpostTradeView? _trade;
    private EntityUid? _console;
    private EntityUid? _grid;
    private List<WFOutpostBuyerView> _buyers = new();

    public WFOutpostConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Tabs.SetTabTitle(0, Loc.GetString("wf-outpost-console-tab-overview"));
        Tabs.SetTabTitle(1, Loc.GetString("wf-outpost-console-tab-saves"));
        Tabs.SetTabTitle(2, Loc.GetString("wf-outpost-console-tab-trade"));
        Tabs.SetTabTitle(3, Loc.GetString("wf-outpost-console-tab-sell"));
        Tabs.SetTabTitle(4, Loc.GetString("wf-outpost-console-tab-access"));
        NameEdit.IsValid = text => text.Length <= WFOutpostLimits.NameLength;
        RenameButton.OnPressed += _ => OnRename?.Invoke(NameEdit.Text);
        NameEdit.OnTextEntered += args => OnRename?.Invoke(args.Text);
        CancelLoadButton.OnPressed += _ => OnCancelLoad?.Invoke();
        SavesHint.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("wf-outpost-console-saves-hint")));
        TradeSearch.OnTextChanged += _ => FilterCatalogue();
        SellHint.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("wf-outpost-sell-hint")));
        SellButton.OnPressed += _ => OnSell?.Invoke();
        SellAtRoundEndCheck.OnToggled += args => OnSellAtRoundEnd?.Invoke(args.Pressed);
        BuyerOption.OnItemSelected += args => BuyerOption.SelectId(args.Id);
        OfferPriceEdit.IsValid = text => text.Length == 0 || int.TryParse(text, out var price)
            && price >= 0 && price <= WFOutpostLimits.MaxOfferPrice;
        OfferButton.OnPressed += _ => SendOffer();
        RefreshBuyersButton.OnPressed += _ => OnRefreshBuyers?.Invoke();
        WithdrawOfferButton.OnPressed += _ => OnWithdrawOffer?.Invoke();
        BuildLegend();
        BuildCatalogue();
    }

    /// <summary>A card: a dark angled panel round a row of content.</summary>
    private static PanelContainer Card(Control content)
    {
        var card = new PanelContainer { HorizontalExpand = true };
        card.AddStyleClass("AngleRect");
        content.Margin = new Thickness(8, 6);
        card.AddChild(content);
        return card;
    }

    /// <summary>
    /// A card with its heading and buttons on the top line and its lines below at the card's full width, so a long line
    /// neither runs under the buttons nor wraps into the line after it.
    /// </summary>
    private static PanelContainer ButtonCard(string heading, IEnumerable<Control> lines, params Control[] buttons)
    {
        var top = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
        var label = new Label
        {
            Text = heading,
            ClipText = true,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        };
        label.AddStyleClass("LabelKeyText");
        top.AddChild(label);
        foreach (var button in buttons)
        {
            top.AddChild(button);
        }

        var column = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 2 };
        column.AddChild(top);
        foreach (var line in lines)
        {
            column.AddChild(line);
        }

        return Card(column);
    }

    private static Label Secondary(string text)
    {
        var label = new Label { Text = text };
        label.AddStyleClass("LabelSecondaryColor");
        return label;
    }

    private void BuildLegend()
    {
        foreach (var (color, text) in new[]
                 {
                     (WFOutpostMapControl.ConsoleColor, "wf-outpost-map-console"),
                     (WFOutpostMapControl.HubColor, "wf-outpost-map-hub"),
                     (WFOutpostMapControl.ClaimColor, "wf-outpost-map-claim"),
                 })
        {
            var entry = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            entry.AddChild(new PanelContainer
            {
                MinSize = new Vector2(10, 10),
                VerticalAlignment = VAlignment.Center,
                PanelOverride = new StyleBoxFlat { BackgroundColor = color },
            });
            var label = new Label { Text = Loc.GetString(text) };
            label.AddStyleClass("LabelSubText");
            entry.AddChild(label);
            MapLegend.AddChild(entry);
        }
    }

    /// <summary>Fills a cap bar and colours it by how close the outpost is to the cap.</summary>
    private static void SetCap(ProgressBar bar, int count, int max)
    {
        var fill = max > 0 ? Math.Clamp((float) count / max, 0f, 1f) : 0f;
        bar.Value = fill;
        bar.ForegroundStyleBoxOverride = new StyleBoxFlat
        {
            BackgroundColor = fill >= 0.95f ? BadColor : fill >= 0.75f ? WarnColor : GoodColor,
        };
    }

    /// <summary>Points the Access tab at the console and the outpost grid it stands on.</summary>
    public void SetConsole(EntityUid console, EntityUid? grid)
    {
        if (_console == console && _grid == grid)
            return;

        _console = console;
        _grid = grid;
        AccessTab.SetShuttle(grid);
        AccessTab.SetConsole(console);
    }

    public void UpdateState(WFOutpostConsoleState state)
    {
        var isOwner = _player.LocalSession?.UserId == state.Owner;
        if (!NameEdit.HasKeyboardFocus())
            NameEdit.Text = state.Name;
        NameEdit.Editable = isOwner;
        RenameButton.Disabled = !isOwner;
        OwnerLabel.Text = state.OwnerName;
        TilesLabel.Text = Loc.GetString("wf-outpost-console-count", ("count", state.Tiles), ("max", state.MaxTiles));
        EntitiesLabel.Text = Loc.GetString("wf-outpost-console-count", ("count", state.Entities), ("max", state.MaxEntities));
        SetCap(TilesBar, state.Tiles, state.MaxTiles);
        SetCap(EntitiesBar, state.Entities, state.MaxEntities);
        OutpostMap.SetGrid(_grid, state.ClaimMargin);
        OutpostMap.SetMarkers(_console, _entMan.GetEntity(state.Hub));

        _raid = state.Raid;
        RaidTitle.Visible = RaidLabel.Visible = _raid != null;
        UpdateRaid();

        _pending = state.Pending;
        PendingBox.Visible = _pending != null;
        CancelLoadButton.Disabled = !isOwner;
        UpdatePending();
        UpdateTrade(state.Trade, isOwner);
        UpdateSale(state.Sale, isOwner, state.Busy || state.Pending != null);

        ReadingLabel.Visible = state.Slots == null;
        SlotsBox.RemoveAllChildren();
        if (state.Slots == null)
            return;

        var locked = !isOwner || state.Busy || state.Pending != null;
        for (var i = 0; i < state.Slots.Count; i++)
        {
            SlotsBox.AddChild(BuildSlot(i, state.Slots[i], locked, isOwner));
        }

        var presets = new Label { Text = Loc.GetString("wf-outpost-presets-title"), Margin = new Thickness(0, 6, 0, 0) };
        presets.AddStyleClass("LabelHeading");
        SlotsBox.AddChild(presets);
        foreach (var preset in _proto.EnumeratePrototypes<WFOutpostPresetPrototype>().OrderBy(p => p.Order).ThenBy(p => p.ID))
        {
            SlotsBox.AddChild(BuildPreset(preset, locked));
        }
    }

    private Control BuildPreset(WFOutpostPresetPrototype preset, bool locked)
    {
        var preview = new Button { Text = Loc.GetString("wf-outpost-console-preview") };
        preview.OnPressed += _ => PreviewBox.ShowPreset(preset);

        var load = new Button { Text = Loc.GetString("wf-outpost-console-load"), Disabled = locked };
        load.OnPressed += _ => OnLoadPreset?.Invoke(preset.ID);

        var description = new FormattedMessage();
        description.PushColor(Color.DarkGray);
        description.AddText(Loc.GetString(preset.Description));
        description.Pop();
        var descriptionLabel = new RichTextLabel();
        descriptionLabel.SetMessage(description);

        var price = Secondary(Loc.GetString("wf-outpost-console-slot-price", ("price", preset.Price)));
        return ButtonCard(Loc.GetString(preset.Name), new Control[] { descriptionLabel, price }, preview, load);
    }

    private Control BuildSlot(int index, WFOutpostSaveSlot? slot, bool locked, bool isOwner)
    {
        var title = Loc.GetString("wf-outpost-console-slot", ("slot", index + 1));
        var name = slot?.Name ?? Loc.GetString("wf-outpost-console-slot-empty");

        var save = new ConfirmButton
        {
            Text = Loc.GetString(slot == null ? "wf-outpost-console-save" : "wf-outpost-console-overwrite"),
            Disabled = locked,
        };
        save.OnPressed += _ => OnSave?.Invoke(index);

        if (slot == null)
            return ButtonCard($"{title}: {name}", Array.Empty<Control>(), save);

        // A preview reads the viewer's own saves, so only the owner gets one of these.
        var preview = new Button { Text = Loc.GetString("wf-outpost-console-preview"), Disabled = !isOwner };
        preview.OnPressed += _ => PreviewBox.ShowSlot(index, slot.Name);

        var load = new Button { Text = Loc.GetString("wf-outpost-console-load"), Disabled = locked || slot.InUse };
        load.OnPressed += _ => OnLoad?.Invoke(index);

        var delete = new ConfirmButton { Text = Loc.GetString("wf-outpost-console-delete"), Disabled = locked };
        delete.AddStyleClass("Caution");
        delete.OnPressed += _ => OnDelete?.Invoke(index);

        var details = Secondary(Loc.GetString("wf-outpost-console-slot-details", ("tiles", slot.Tiles),
            ("entities", slot.Entities), ("saved", slot.Saved.ToLocalTime().ToString("g"))));
        var price = Secondary(slot.InUse
            ? Loc.GetString("wf-outpost-console-slot-in-use")
            : Loc.GetString("wf-outpost-console-slot-price", ("price", slot.Price)));
        return ButtonCard($"{title}: {name}", new Control[] { details, price }, save, preview, load, delete);
    }

    /// <summary>One row per listing in the outpost trade group, by category and then name.</summary>
    private void BuildCatalogue()
    {
        var products = _proto.EnumeratePrototypes<CargoProductPrototype>()
            .Where(p => p.Group == WFOutpostLimits.TradeGroup)
            .OrderBy(p => Loc.GetString(p.Category))
            .ThenBy(p => p.Name);

        foreach (var product in products)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
            var icon = new EntityPrototypeView { SetSize = new Vector2(48, 48), Scale = new Vector2(1.5f, 1.5f) };
            icon.SetPrototype(product.Product);
            row.AddChild(icon);

            var text = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            };
            var title = new Label { Text = product.Name, ClipText = true };
            title.AddStyleClass("LabelKeyText");
            text.AddChild(title);
            var category = new Label { Text = Loc.GetString(product.Category), ClipText = true };
            category.AddStyleClass("LabelSecondaryColor");
            text.AddChild(category);
            row.AddChild(text);

            var order = new Button
            {
                Text = Loc.GetString("wf-outpost-trade-order", ("cost", product.Cost)),
                ToolTip = product.Description,
                Disabled = true,
                MinWidth = 120,
                VerticalAlignment = VAlignment.Center,
            };
            var id = product.ID;
            order.OnPressed += _ => OnOrder?.Invoke(id);
            row.AddChild(order);

            var card = Card(row);
            CatalogueBox.AddChild(card);
            _listings.Add((product, order, card));
        }
    }

    private void FilterCatalogue()
    {
        var search = TradeSearch.Text.Trim();
        foreach (var (product, _, row) in _listings)
        {
            row.Visible = search.Length == 0 || product.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase);
        }
    }

    private void UpdateTrade(WFOutpostTradeView trade, bool isOwner)
    {
        _trade = trade;
        var hubText = Loc.GetString(trade.Hub switch
        {
            WFOutpostHubStatus.None => "wf-outpost-trade-hub-none",
            WFOutpostHubStatus.Unpowered => "wf-outpost-trade-hub-unpowered",
            WFOutpostHubStatus.Covered => "wf-outpost-trade-hub-covered",
            _ => "wf-outpost-trade-hub-ready",
        });
        var hubColor = trade.Hub switch
        {
            WFOutpostHubStatus.Ready => GoodColor,
            WFOutpostHubStatus.None => BadColor,
            _ => WarnColor,
        };
        HubLabel.Text = OverviewHubLabel.Text = hubText;
        HubLabel.FontColorOverride = OverviewHubLabel.FontColorOverride = hubColor;
        OverviewHubLabel.ToolTip = hubText;
        OverviewOrdersLabel.Text = Loc.GetString("wf-outpost-console-count", ("count", trade.Orders.Count),
            ("max", WFOutpostLimits.OrdersInFlight));
        BalanceLabel.Text = Loc.GetString("wf-outpost-trade-credits", ("credits", trade.Balance));
        OrdersHeader.Text = Loc.GetString("wf-outpost-trade-orders", ("count", trade.Orders.Count), ("max", WFOutpostLimits.OrdersInFlight));

        var open = isOwner && trade.Hub == WFOutpostHubStatus.Ready && trade.Orders.Count < WFOutpostLimits.OrdersInFlight;
        foreach (var (product, order, _) in _listings)
        {
            order.Disabled = !open || product.Cost > trade.Balance;
        }

        UpdateOrders();
    }

    private void UpdateOrders()
    {
        if (_trade == null)
            return;

        while (_orderLabels.Count < _trade.Orders.Count)
        {
            var added = new Label { ClipText = true };
            added.AddStyleClass("LabelSecondaryColor");
            OrdersBox.AddChild(added);
            _orderLabels.Add(added);
        }

        while (_orderLabels.Count > _trade.Orders.Count)
        {
            OrdersBox.RemoveChild(_orderLabels[^1]);
            _orderLabels.RemoveAt(_orderLabels.Count - 1);
        }

        for (var i = 0; i < _trade.Orders.Count; i++)
        {
            var order = _trade.Orders[i];
            var name = _proto.TryIndex<CargoProductPrototype>(order.Product, out var product) ? product.Name : order.Product;
            var seconds = Math.Max(0, (int) Math.Ceiling((order.Drops - _timing.CurTime).TotalSeconds));
            _orderLabels[i].Text = order.Falling || seconds == 0
                ? Loc.GetString("wf-outpost-trade-order-falling", ("name", name))
                : Loc.GetString("wf-outpost-trade-order-due", ("name", name), ("seconds", seconds));
        }
    }

    private void UpdateSale(WFOutpostSaleView sale, bool isOwner, bool locked)
    {
        SellValueLabel.Text = Loc.GetString("wf-outpost-trade-credits", ("credits", sale.Value));
        SellButton.Disabled = !isOwner || locked;
        SellAtRoundEndCheck.Pressed = sale.SellAtRoundEnd;
        SellAtRoundEndCheck.Disabled = !isOwner;

        var selected = BuyerOption.SelectedId >= 0 && BuyerOption.SelectedId < _buyers.Count
            ? _buyers[BuyerOption.SelectedId].User
            : (NetUserId?) null;
        _buyers = sale.Buyers;
        BuyerOption.Clear();
        if (_buyers.Count == 0)
            BuyerOption.AddItem(Loc.GetString("wf-outpost-offer-no-buyers"), 0);
        for (var i = 0; i < _buyers.Count; i++)
        {
            BuyerOption.AddItem(_buyers[i].Name, i);
            if (_buyers[i].User == selected)
                BuyerOption.SelectId(i);
        }

        BuyerOption.Disabled = _buyers.Count == 0;
        OfferButton.Disabled = !isOwner || locked || _buyers.Count == 0;
        OfferBox.Visible = sale.Offer != null;
        WithdrawOfferButton.Disabled = !isOwner;
        if (sale.Offer is { } offer)
            OfferLabel.Text = Loc.GetString("wf-outpost-offer-standing", ("buyer", offer.BuyerName), ("price", offer.Price));
    }

    private void SendOffer()
    {
        if (BuyerOption.SelectedId < 0 || BuyerOption.SelectedId >= _buyers.Count
            || !int.TryParse(OfferPriceEdit.Text, out var price))
            return;

        OnOffer?.Invoke(_buyers[BuyerOption.SelectedId].User, price);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdatePending();
        UpdateRaid();
        if (Tabs.CurrentTab == 2)
            UpdateOrders();
    }

    /// <summary>Counts the raid window down to when it opens or closes.</summary>
    private void UpdateRaid()
    {
        if (_raid == null)
            return;

        if (_raid.Changes is not { } changes)
        {
            RaidLabel.Text = Loc.GetString(_raid.Active ? "wf-outpost-console-raids-always" : "wf-outpost-console-raids-never");
            return;
        }

        var minutes = Math.Max(0, (int) Math.Ceiling((changes - _timing.CurTime).TotalMinutes));
        RaidLabel.Text = Loc.GetString(_raid.Active ? "wf-outpost-console-raids-active" : "wf-outpost-console-raids-quiet",
            ("minutes", minutes));
    }

    private void UpdatePending()
    {
        if (_pending == null)
            return;

        var seconds = Math.Max(0, (int) Math.Ceiling((_pending.Lands - _timing.CurTime).TotalSeconds));
        PendingLabel.Text = Loc.GetString("wf-outpost-console-pending",
            ("name", _pending.Name), ("seconds", seconds), ("price", _pending.Price));
    }
}
