using Content.Shared._WF.Feedback;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.Feedback;

/// <summary>Tells the player which of their reports staff have moved on, and what staff wrote back.</summary>
[GenerateTypedNameReferences]
public sealed partial class FeedbackNoticeWindow : DefaultWindow
{
    /// <summary>The reports this notice covers.</summary>
    public readonly List<int> Ids = new();

    public FeedbackNoticeWindow()
    {
        RobustXamlLoader.Load(this);
        OkButton.OnPressed += _ => Close();
    }

    public FeedbackNoticeWindow(List<FeedbackEntry> reports) : this()
    {
        foreach (var report in reports)
        {
            Ids.Add(report.Id);
            Reports.AddChild(new FeedbackEntryRow(report));
        }
    }
}
