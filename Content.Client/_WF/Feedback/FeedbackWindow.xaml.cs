using Content.Client.Message;
using Content.Shared._WF.Feedback;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WF.Feedback;

/// <summary>The form a player fills in to send a bug report or a suggestion, and the list of what they have sent.</summary>
[GenerateTypedNameReferences]
public sealed partial class FeedbackWindow : DefaultWindow
{
    private FeedbackKind _kind = FeedbackKind.Bug;
    private bool _sending;

    /// <summary>Raised with a report that passed the window's own checks.</summary>
    public event Action<FeedbackSubmitEvent>? Submitted;

    /// <summary>Raised when the player's own reports should be asked for again.</summary>
    public event Action? HistoryRequested;

    /// <summary>Whether the player wants the screenshot sent along.</summary>
    public bool AttachScreenshot => ScreenshotCheck.Visible && ScreenshotCheck.Pressed;

    public FeedbackWindow()
    {
        RobustXamlLoader.Load(this);

        var tabs = new ButtonGroup();
        BugTab.Group = tabs;
        SuggestionTab.Group = tabs;
        HistoryTab.Group = tabs;
        BugTab.OnPressed += _ => SetKind(FeedbackKind.Bug);
        SuggestionTab.OnPressed += _ => SetKind(FeedbackKind.Suggestion);
        HistoryTab.OnPressed += _ => ShowHistoryTab();

        for (var i = 0; i < FeedbackRules.Categories.Length; i++)
        {
            CategoryOption.AddItem(Loc.GetString($"wf-feedback-category-{FeedbackRules.Categories[i]}"), i);
        }

        CategoryOption.SelectId(Array.IndexOf(FeedbackRules.Categories, FeedbackRules.DefaultCategory));
        CategoryOption.OnItemSelected += args => CategoryOption.SelectId(args.Id);

        foreach (var severity in Enum.GetValues<FeedbackSeverity>())
        {
            SeverityOption.AddItem(Loc.GetString($"wf-feedback-severity-{severity.ToString().ToLowerInvariant()}"), (int) severity);
        }

        SeverityOption.OnItemSelected += args => SeverityOption.SelectId(args.Id);

        TitleEdit.PlaceHolder = Loc.GetString("wf-feedback-title-placeholder");
        TitleEdit.IsValid = text => text.Length <= FeedbackRules.MaxTitle;
        AttachedNote.SetMarkup(Loc.GetString("wf-feedback-attached-note"));
        SubmitButton.OnPressed += _ => Submit();
        SetKind(FeedbackKind.Bug);
    }

    /// <summary>Shows the screenshot option once there is a screenshot to send.</summary>
    public void SetScreenshotReady(bool ready)
    {
        ScreenshotCheck.Visible = ready;
    }

    /// <summary>Shows the server's answer. A stored report empties the form for the next one.</summary>
    public void ShowResult(FeedbackResultEvent result)
    {
        _sending = false;
        SubmitButton.Disabled = false;

        if (result.Error != null)
        {
            ShowError(Loc.GetString(result.Error, ("seconds", result.RetrySeconds)));
            return;
        }

        TitleEdit.Clear();
        DescriptionEdit.TextRope = Rope.Leaf.Empty;
        StepsEdit.TextRope = Rope.Leaf.Empty;
        ExpectedEdit.TextRope = Rope.Leaf.Empty;
        StatusLabel.SetMarkup(Loc.GetString("wf-feedback-sent", ("id", result.ReportId.ToString())));
    }

    /// <summary>Fills the My reports tab.</summary>
    public void ShowHistory(List<FeedbackEntry> reports)
    {
        HistoryList.RemoveAllChildren();
        HistoryNote.Text = Loc.GetString("wf-feedback-history-empty");
        HistoryNote.Visible = reports.Count == 0;
        foreach (var report in reports)
        {
            HistoryList.AddChild(new FeedbackEntryRow(report));
        }
    }

    private void ShowHistoryTab()
    {
        FormBox.Visible = false;
        HistoryBox.Visible = true;
        HistoryRequested?.Invoke();
    }

    private void SetKind(FeedbackKind kind)
    {
        _kind = kind;
        FormBox.Visible = true;
        HistoryBox.Visible = false;
        var bug = kind == FeedbackKind.Bug;
        BugFields.Visible = bug;
        SeverityLabel.Visible = bug;
        SeverityOption.Visible = bug;
        DescriptionLabel.Text = Loc.GetString(bug ? "wf-feedback-description-bug" : "wf-feedback-description-suggestion");
        DescriptionEdit.Placeholder = new Rope.Leaf(Loc.GetString(bug
            ? "wf-feedback-description-bug-placeholder"
            : "wf-feedback-description-suggestion-placeholder"));
        StepsEdit.Placeholder = new Rope.Leaf(Loc.GetString("wf-feedback-steps-placeholder"));
        ExpectedEdit.Placeholder = new Rope.Leaf(Loc.GetString("wf-feedback-expected-placeholder"));
    }

    /// <summary>Checks the form and sends it, as the Send button does.</summary>
    public void Submit()
    {
        if (_sending)
            return;

        var bug = _kind == FeedbackKind.Bug;
        var report = new FeedbackSubmitEvent
        {
            Kind = _kind,
            Category = FeedbackRules.Categories[CategoryOption.SelectedId],
            Severity = bug ? (FeedbackSeverity) SeverityOption.SelectedId : FeedbackSeverity.Minor,
            Title = TitleEdit.Text.Trim(),
            Description = Rope.Collapse(DescriptionEdit.TextRope).Trim(),
            Steps = bug ? Rope.Collapse(StepsEdit.TextRope).Trim() : string.Empty,
            Expected = bug ? Rope.Collapse(ExpectedEdit.TextRope).Trim() : string.Empty,
        };

        if (FeedbackRules.Validate(report) is { } problem)
        {
            ShowError(Loc.GetString(problem));
            return;
        }

        _sending = true;
        SubmitButton.Disabled = true;
        StatusLabel.SetMarkup(Loc.GetString("wf-feedback-sending"));
        Submitted?.Invoke(report);
    }

    private void ShowError(string text)
    {
        StatusLabel.SetMarkup(Loc.GetString("wf-feedback-error", ("error", FormattedMessage.EscapeText(text))));
    }
}
