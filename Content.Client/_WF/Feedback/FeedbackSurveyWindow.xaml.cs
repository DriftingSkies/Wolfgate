using Content.Client.Message;
using Content.Shared._WF.Feedback;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WF.Feedback;

/// <summary>The end of shift survey: how much the player enjoyed it, the issues they hit and what frustrated them.</summary>
[GenerateTypedNameReferences]
public sealed partial class FeedbackSurveyWindow : DefaultWindow
{
    private readonly List<Button> _ratings = new();
    private bool _sending;

    /// <summary>What offered this survey.</summary>
    public FeedbackSurveyTrigger Trigger;

    /// <summary>The enjoyment the player picked, or 0.</summary>
    public int Rating { get; private set; }

    /// <summary>Whether the survey has been stored.</summary>
    public bool Sent { get; private set; }

    /// <summary>Raised with a survey that has a rating.</summary>
    public event Action<FeedbackSubmitEvent>? Submitted;

    public FeedbackSurveyWindow()
    {
        RobustXamlLoader.Load(this);

        var group = new ButtonGroup();
        for (var i = 1; i <= FeedbackRules.MaxRating; i++)
        {
            var rating = i;
            var button = new Button
            {
                Text = Loc.GetString($"wf-feedback-survey-rating-{rating}"),
                ToggleMode = true,
                Group = group,
                HorizontalExpand = true,
            };
            button.OnPressed += _ => Rating = rating;
            _ratings.Add(button);
            RatingButtons.AddChild(button);
        }

        IssuesEdit.Placeholder = new Rope.Leaf(Loc.GetString("wf-feedback-survey-issues-placeholder"));
        FrustrationsEdit.Placeholder = new Rope.Leaf(Loc.GetString("wf-feedback-survey-frustrations-placeholder"));
        AttachedNote.SetMarkup(Loc.GetString("wf-feedback-survey-note"));
        SubmitButton.OnPressed += _ => Submit();
    }

    /// <summary>Picks a rating, as pressing its button does.</summary>
    public void SetRating(int rating)
    {
        Rating = rating;
        for (var i = 0; i < _ratings.Count; i++)
        {
            _ratings[i].Pressed = i + 1 == rating;
        }
    }

    /// <summary>Checks the survey and sends it, as the Send button does.</summary>
    public void Submit()
    {
        if (_sending || Sent)
            return;

        var survey = new FeedbackSubmitEvent
        {
            Kind = FeedbackKind.Survey,
            Rating = Rating,
            Trigger = Trigger,
            Description = Rope.Collapse(IssuesEdit.TextRope).Trim(),
            Frustrations = Rope.Collapse(FrustrationsEdit.TextRope).Trim(),
        };

        if (FeedbackRules.Validate(survey) is { } problem)
        {
            ShowError(Loc.GetString(problem));
            return;
        }

        _sending = true;
        SubmitButton.Disabled = true;
        StatusLabel.SetMarkup(Loc.GetString("wf-feedback-sending"));
        Submitted?.Invoke(survey);
    }

    /// <summary>Shows the server's answer.</summary>
    public void ShowResult(FeedbackResultEvent result)
    {
        _sending = false;
        if (result.Error != null)
        {
            SubmitButton.Disabled = false;
            ShowError(Loc.GetString(result.Error, ("seconds", result.RetrySeconds)));
            return;
        }

        Sent = true;
        StatusLabel.SetMarkup(Loc.GetString("wf-feedback-survey-sent", ("id", result.ReportId.ToString())));
    }

    private void ShowError(string text)
    {
        StatusLabel.SetMarkup(Loc.GetString("wf-feedback-error", ("error", FormattedMessage.EscapeText(text))));
    }
}
